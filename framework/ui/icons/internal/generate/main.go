// Command generate validates the source SVGs and writes the Go icon catalog.
package main

import (
	"bytes"
	"crypto/rand"
	"encoding/xml"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"io"
	"maps"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strconv"
	"strings"
)

var (
	namePattern   = regexp.MustCompile(`^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$`)
	numberPattern = regexp.MustCompile(`^[0-9eE.,+\s-]+$`)
	pathPattern   = regexp.MustCompile(`^[MmLlHhVvCcSsQqTtAaZz0-9eE.,+\s-]+$`)
)

func main() {
	if err := generate(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate() error {
	manifest, license, err := loadSources(".")
	if err != nil {
		return err
	}
	root, err := os.OpenRoot(".")
	if err != nil {
		return err
	}
	defer root.Close()
	identifiers, err := handwrittenIdentifiers()
	if err != nil {
		return err
	}
	reserve := func(name string) error {
		ident := identifier(name)
		if previous, exists := identifiers[ident]; exists {
			return fmt.Errorf("icon %q generates Go identifier %q already declared by %s", name, ident, previous)
		}
		identifiers[ident] = "icon " + name
		return nil
	}
	files, err := filepath.Glob("svg/*.svg")
	if err != nil {
		return err
	}
	slices.SortFunc(files, func(a, b string) int {
		return strings.Compare(strings.TrimSuffix(filepath.Base(a), ".svg"), strings.TrimSuffix(filepath.Base(b), ".svg"))
	})
	if len(files) == 0 {
		return fmt.Errorf("no icon sources in svg/")
	}
	if len(files) != len(manifest.Icons) {
		return fmt.Errorf("SVG files and sources.json differ; record every vendored icon")
	}
	byName := make(map[string]sourceIcon, len(manifest.Icons))
	for _, source := range manifest.Icons {
		byName[source.Name] = source
	}
	var out bytes.Buffer
	out.WriteString("// Code generated by go generate; DO NOT EDIT.\n//\n")
	for _, source := range manifest.Sources {
		fmt.Fprintf(&out, "// SVG source: %s at %s\n// Source first retrieved: %s.\n", source.RepositoryURL, source.Commit, source.RetrievedAt)
	}
	out.WriteString("// Per-icon retrieval times, mappings, aliases and SHA-256 hashes: sources.json.\n// Geometry is extracted without editing coordinates.\n//\n")
	for _, line := range strings.Split(strings.TrimSpace(license), "\n") {
		fmt.Fprintf(&out, "// %s\n", strings.TrimSuffix(line, "\r"))
	}
	out.WriteString("\npackage icons\n\nconst (\n")
	bodies := make([]string, len(files))
	names := make([]string, len(files))
	for i, file := range files {
		name := strings.TrimSuffix(filepath.Base(file), ".svg")
		if !namePattern.MatchString(name) {
			return fmt.Errorf("invalid or reserved icon name %q", name)
		}
		if err := reserve(name); err != nil {
			return err
		}
		sourceRecord, ok := byName[name]
		if !ok {
			return fmt.Errorf("%s has no sources.json entry", file)
		}
		source, err := readVerifiedSVG(root, file, sourceRecord.SHA256)
		if err != nil {
			return err
		}
		body, err := validate(source)
		if err != nil {
			return fmt.Errorf("%s: %w", file, err)
		}
		names[i], bodies[i] = name, body
		ident := identifier(name)
		fmt.Fprintf(&out, "// %s names the %s icon, from %s %s.\n%s = %q\n", ident, name, sourceRecord.Source, sourceRecord.UpstreamPath, ident, name)
	}
	for _, alias := range slices.Sorted(maps.Keys(manifest.Aliases)) {
		if err := reserve(alias); err != nil {
			return err
		}
		fmt.Fprintf(&out, "// %s aliases %s.\n%s = %q\n", identifier(alias), identifier(manifest.Aliases[alias]), identifier(alias), alias)
	}
	out.WriteString(")\n\nvar names = []string{\n")
	for _, name := range names {
		fmt.Fprintf(&out, "%q,\n", name)
	}
	out.WriteString("}\n\nvar bodies = map[string]string{\n")
	for i, name := range names {
		fmt.Fprintf(&out, "%q: %s,\n", name, strconv.Quote(bodies[i]))
	}
	out.WriteString("}\n")
	out.WriteString("\nvar aliases = map[string]string{\n")
	for _, alias := range slices.Sorted(maps.Keys(manifest.Aliases)) {
		fmt.Fprintf(&out, "%q: %q,\n", alias, manifest.Aliases[alias])
	}
	out.WriteString("}\n")
	formatted, err := format.Source(out.Bytes())
	if err != nil {
		return err
	}
	return writeGenerated(formatted)
}

func readVerifiedSVG(root *os.Root, file, checksum string) ([]byte, error) {
	data, err := root.ReadFile(file)
	if err != nil {
		return nil, err
	}
	if !matchesSHA256(data, checksum) {
		return nil, fmt.Errorf("%s differs from its recorded upstream SHA-256", file)
	}
	return data, nil
}

func writeGenerated(data []byte) error {
	root, err := os.OpenRoot(".")
	if err != nil {
		return err
	}
	defer root.Close()
	if info, err := root.Lstat("icons_gen.go"); err == nil {
		if info.Mode()&os.ModeSymlink != 0 || !info.Mode().IsRegular() {
			return fmt.Errorf("icons_gen.go must be a regular file, not a symlink or directory")
		}
	} else if !os.IsNotExist(err) {
		return err
	}
	temp := ".icons-gen-" + rand.Text() + ".tmp"
	file, err := root.OpenFile(temp, os.O_CREATE|os.O_EXCL|os.O_WRONLY, 0644)
	if err != nil {
		return err
	}
	defer root.Remove(temp)
	if _, err := file.Write(data); err != nil {
		file.Close()
		return err
	}
	if err := file.Close(); err != nil {
		return err
	}
	return root.Rename(temp, "icons_gen.go")
}

// Reserve declarations from every handwritten package file, including files
// selected only on another platform. A generated constant must build with all
// of them. Do not parse the old generated file or test-only declarations.
func handwrittenIdentifiers() (map[string]string, error) {
	result := map[string]string{}
	files, err := filepath.Glob("*.go")
	if err != nil {
		return nil, err
	}
	for _, file := range files {
		if file == "icons_gen.go" || strings.HasSuffix(file, "_test.go") {
			continue
		}
		source, err := parser.ParseFile(token.NewFileSet(), file, nil, 0)
		if err != nil {
			return nil, err
		}
		for _, decl := range source.Decls {
			switch decl := decl.(type) {
			case *ast.FuncDecl:
				if decl.Recv == nil {
					result[decl.Name.Name] = file
				}
			case *ast.GenDecl:
				for _, spec := range decl.Specs {
					switch spec := spec.(type) {
					case *ast.TypeSpec:
						result[spec.Name.Name] = file
					case *ast.ValueSpec:
						for _, name := range spec.Names {
							result[name.Name] = file
						}
					}
				}
			}
		}
	}
	return result, nil
}

func identifier(name string) string {
	var out strings.Builder
	for _, part := range strings.Split(name, "-") {
		out.WriteString(strings.ToUpper(part[:1]))
		out.WriteString(part[1:])
	}
	return out.String()
}

// validate admits drawing geometry only. Source SVGs cannot contribute scripts,
// styles, links, accessibility labels, or attributes that alter the shared pen.
func validate(source []byte) (string, error) {
	d := xml.NewDecoder(bytes.NewReader(source))
	var body bytes.Buffer
	e := xml.NewEncoder(&body)
	depth, roots, shapes := 0, 0, 0
	for {
		token, err := d.Token()
		if err == io.EOF {
			break
		}
		if err != nil {
			return "", err
		}
		switch t := token.(type) {
		case xml.StartElement:
			if depth == 0 {
				roots++
				if roots != 1 || t.Name.Local != "svg" || t.Name.Space != "http://www.w3.org/2000/svg" {
					return "", fmt.Errorf("expected one SVG root")
				}
				want := map[string]string{"xmlns": "http://www.w3.org/2000/svg", "viewBox": "0 0 24 24", "fill": "none", "stroke": "currentColor", "stroke-width": "2", "stroke-linecap": "round", "stroke-linejoin": "round", "width": "24", "height": "24"}
				for _, attr := range t.Attr {
					value, ok := want[attr.Name.Local]
					if attr.Name.Space != "" || !ok || value != attr.Value {
						return "", fmt.Errorf("unexpected root attribute %q", attr.Name.Local)
					}
					delete(want, attr.Name.Local)
				}
				// Standalone upstream SVGs include 24px dimensions; the
				// shared renderer replaces these with IconConfig.Size.
				delete(want, "width")
				delete(want, "height")
				if len(want) != 0 {
					return "", fmt.Errorf("missing shared SVG drawing attributes")
				}
			} else {
				allowed := map[string]string{"path": " d ", "circle": " cx cy r ", "rect": " x y width height rx ry ", "line": " x1 y1 x2 y2 ", "polyline": " points ", "polygon": " points ", "ellipse": " cx cy rx ry "}
				attrs, ok := allowed[t.Name.Local]
				if depth != 1 || !ok || t.Name.Space != "http://www.w3.org/2000/svg" || len(t.Attr) == 0 {
					return "", fmt.Errorf("unsupported drawing element %q", t.Name.Local)
				}
				seen := map[string]bool{}
				for _, attr := range t.Attr {
					pattern := numberPattern
					if attr.Name.Local == "d" {
						pattern = pathPattern
					}
					if attr.Name.Space != "" || seen[attr.Name.Local] || !strings.Contains(attrs, " "+attr.Name.Local+" ") || !pattern.MatchString(attr.Value) {
						return "", fmt.Errorf("unsupported geometry attribute %q", attr.Name.Local)
					}
					seen[attr.Name.Local] = true
				}
				shapes++
				t.Name.Space = ""
				if err := e.EncodeToken(t); err != nil {
					return "", err
				}
			}
			depth++
		case xml.EndElement:
			depth--
			if depth > 0 {
				t.Name.Space = ""
				if err := e.EncodeToken(t); err != nil {
					return "", err
				}
			}
		case xml.CharData:
			if strings.TrimSpace(string(t)) != "" {
				return "", fmt.Errorf("drawing contains text")
			}
		default:
			return "", fmt.Errorf("drawing contains a comment, directive or processing instruction")
		}
	}
	if roots != 1 || depth != 0 || shapes == 0 {
		return "", fmt.Errorf("expected a nonempty SVG drawing")
	}
	if err := e.Flush(); err != nil {
		return "", err
	}
	return body.String(), nil
}
