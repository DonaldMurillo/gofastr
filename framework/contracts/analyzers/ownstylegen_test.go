package analyzers_test

import (
	"testing"

	"github.com/DonaldMurillo/gofastr/core-ui/ownstyle"
	"github.com/DonaldMurillo/gofastr/framework/contracts"
)

// GOFASTR1814 pins the pair every owned style lives in: the
// hand-written <name>.style.css and the generated
// <name>_style.gen.go whose Source hash line freezes the CSS bytes the
// Go embeds. The fixtures here exercise the three states the rule
// distinguishes: no sibling, a stale sibling, a fresh sibling.

const styleGenCSS = "/* One card. */\n:scope { display: grid; gap: var(--spacing-xs); }\n.key { color: var(--color-text-muted); }\n"

func styleGenGolden(css string) string {
	// The shape gen styles writes, with the CURRENT hash: a real
	// generated file's bytes are produced by core-ui/ownstyle against
	// an empty model, which is all the rule reads.
	m := &ownstyle.SheetModel{}
	out, err := ownstyle.GenerateFile("board", ownstyle.KindScoped, css, m, "ui", false)
	if err != nil {
		return "// Code generated by \"gofastr gen styles\" from board.style.css. DO NOT EDIT.\n// Source hash: sha256:" + ownstyle.SourceHash(css) + "\n\npackage ui\n"
	}
	return out
}

// A .style.css with no sibling gen file fires, naming both files and
// the fix.
func TestStaleStyleSourceFiresOnMissingSibling(t *testing.T) {
	ds := fixture(t, map[string]string{
		"ui/board.style.css": styleGenCSS,
		"ui/ui.go":           "package ui\n",
	})
	d := assertHas(t, ds, contracts.RuleStaleStyleSource)
	want := "board.style.css has no generated sibling board_style.gen.go; run gofastr gen styles"
	if d.Message != want {
		t.Errorf("message = %q, want %q", d.Message, want)
	}
}

// A sibling whose Source hash does not match the CSS bytes fires with
// the "changed since generated" wording.
func TestStaleStyleSourceFiresOnStaleHash(t *testing.T) {
	ds := fixture(t, map[string]string{
		"ui/board.style.css": styleGenCSS,
		"ui/ui.go":           "package ui\n",
		// A generated file built from DIFFERENT CSS bytes: the hash is
		// well-formed but stale.
		"ui/board_style.gen.go": styleGenGolden(":scope { display: grid; }\n"),
	})
	d := assertHas(t, ds, contracts.RuleStaleStyleSource)
	want := "board.style.css changed since its Go was generated; run gofastr gen styles"
	if d.Message != want {
		t.Errorf("message = %q, want %q", d.Message, want)
	}
}

// A generated file with no Source hash line at all is the same
// failure as a stale one: the pair cannot be proven fresh.
func TestStaleStyleSourceFiresOnHashlessSibling(t *testing.T) {
	ds := fixture(t, map[string]string{
		"ui/board.style.css": styleGenCSS,
		"ui/ui.go":           "package ui\n",
		"ui/board_style.gen.go": "// Code generated by \"gofastr gen styles\" from board.style.css. DO NOT EDIT.\n" +
			"package ui\n\nvar Style = 1\n",
	})
	assertHas(t, ds, contracts.RuleStaleStyleSource)
}

// The quiet state: the sibling exists and its hash matches the CSS
// bytes exactly.
func TestStaleStyleSourceQuietOnFreshPair(t *testing.T) {
	ds := fixture(t, map[string]string{
		"ui/board.style.css":    styleGenCSS,
		"ui/ui.go":              "package ui\n",
		"ui/board_style.gen.go": styleGenGolden(styleGenCSS),
	})
	assertNot(t, ds, contracts.RuleStaleStyleSource, "the generated file's hash matches the CSS bytes")
}

// Ordinary stylesheets (not *.style.css) are not this rule's
// business: they have no generated sibling by design.
func TestStaleStyleSourceIgnoresPlainCSS(t *testing.T) {
	ds := fixture(t, map[string]string{
		"static/app.css": ".a { color: red; }\n",
	})
	assertNot(t, ds, contracts.RuleStaleStyleSource, "a plain stylesheet has no generated sibling by design")
}

// testdata trees hold parser fixtures, not shipped packages; the
// generator itself refuses them (no Go package), so the rule skips
// them like GOFASTR1809's stylesheet loop does.
func TestStaleStyleSourceSkipsTestdata(t *testing.T) {
	ds := fixture(t, map[string]string{
		"testdata/board.style.css": styleGenCSS,
	})
	assertNot(t, ds, contracts.RuleStaleStyleSource, "testdata is not a shipped package")
}
