func TestVettoolBuildNeedsBuildVCSFalse(t *testing.T) {
	cases := []struct {
		name, rel, body string
		want            int
	}{
		{"plain make build", "Makefile", "analyze:\n\tgo build -o dist/vettool ./cmd/vettool\n", 1},
		{"stamped off", "Makefile", "analyze:\n\tgo build -buildvcs=false -o dist/vettool ./cmd/vettool\n", 0},
		{"a hook", ".githooks/pre-commit", "go build -o /tmp/v ./cmd/vettool\n", 1},
		{"a workflow", ".github/workflows/ci.yml", "      - run: go build -o dist/vettool ./cmd/vettool\n", 1},
		{"Go exec form", "tool.go", "package x\nvar c = exec.Command(\"go\", \"build\", \"-o\", out, \"./cmd/vettool\")\n", 1},
		{"a comment is prose", "Makefile", "# go build ./cmd/vettool\n", 0},
		{"another command", "Makefile", "go build ./cmd/vettoolkit\n", 0},
		{"testdata is skipped", "x/testdata/Makefile", "go build ./cmd/vettool\n", 0},
		{"an unlisted extension", "notes.txt", "go build ./cmd/vettool\n", 0},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			root := t.TempDir()
			writeTestFile(t, root, filepath.FromSlash(tc.rel), tc.body)
			findings, err := lintVettoolBuildVCS(root)
			if err != nil {
				t.Fatal(err)
			}
			if len(findings) != tc.want {
				t.Fatalf("got %d findings, want %d: %+v", len(findings), tc.want, findings)
			}
		})
	}
	findings, err := lintRepo(writeRepo(t, "Makefile", "a:\n\tgo build ./cmd/vettool\n"))
	if err != nil {
		t.Fatal(err)
	}
	mustFindRule(t, findings, "vettool-buildvcs")
}

func TestDuplicateURLGuardIsFlagged(t *testing.T) {
	guard := "package x\n\nvar bad = []string{\"%0d\", \"%0a\"}\n"
	cases := []struct {
		rel  string
		want int
	}{
		{"framework/ui/link.go", 3},
		{"core-ui/urlsafe/urlsafe.go", 0},
		{"cmd/repolint/rule.go", 0},
		{"framework/ui/link_test.go", 0},
		{"framework/ui/link.md", 0},
	}
	for _, tc := range cases {
		if got := duplicateURLGuardLine(tc.rel, []byte(guard)); got != tc.want {
			t.Errorf("%s: line %d, want %d", tc.rel, got, tc.want)
		}
	}
	if got := duplicateURLGuardLine("framework/ui/link.go", []byte("package x\nvar s = \"%0d\"\n")); got != 0 {
		t.Errorf("one half of the fingerprint flagged line %d", got)
	}
	findings, err := lintRepo(writeRepo(t, "framework/ui/link.go", guard))
	if err != nil {
		t.Fatal(err)
	}
	mustFindRule(t, findings, "duplicate-url-guard")
}

