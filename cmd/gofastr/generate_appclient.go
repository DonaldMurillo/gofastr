package main

import (
	"fmt"
	"path/filepath"

	"github.com/DonaldMurillo/gofastr/codegen"
	"github.com/DonaldMurillo/gofastr/framework"
)

// appClientPath is where the client generator writes the app's typed Go
// client, relative to the app root (the directory holding entities/).
const appClientPath = "entities/client/client.go"

// renderAppClient renders entities/client/client.go, stamped as the client
// generator's derived output. The app generator writes the first copy
// through the same function, so a fresh app and a later rebuild agree byte
// for byte.
func renderAppClient(decls []framework.EntityDeclaration) (string, error) {
	for _, decl := range decls {
		if err := validateDeclarationStates(decl); err != nil {
			return "", fmt.Errorf("entity %q: %w", decl.Name, err)
		}
	}
	src := "// Code generated by \"gofastr generate client\" from entities/. DO NOT EDIT.\n" +
		"// Add your own code in another file of this package; gofastr build rebuilds this one.\n\n" +
		renderClient(decls)
	if err := refuseDuplicateDecls([]generatedFile{{name: appClientPath, content: src}}); err != nil {
		return "", err
	}
	return stampFile("client", appClientPath, src)
}

// appClientPlan is what a client rebuild would do to the file on disk.
type appClientPlan struct {
	content string
	// unchanged: the file already holds exactly this content.
	unchanged bool
	// owned: the file on disk is the app generator's scaffold copy (or has
	// no marker) and was edited, so it holds code the user wrote. A rebuild
	// discards that code; only an explicit --force may.
	owned bool
}

// planAppClient renders the client for the entities under dir and compares
// it with the file there now. ok is false when dir has no entities package.
func planAppClient(dir string) (plan appClientPlan, ok bool, err error) {
	decls, err := packReadEntities(dir)
	if err != nil {
		return plan, false, fmt.Errorf("read entities: %w", err)
	}
	if len(decls) == 0 {
		return plan, false, nil
	}
	plan.content, err = renderAppClient(decls)
	if err != nil {
		return plan, true, err
	}
	existing, rerr := readFileUnder(dir, appClientPath)
	if rerr != nil {
		return plan, true, nil
	}
	plan.unchanged = string(existing) == plan.content
	if m, _, marked := codegen.ReadMarker(appClientPath, string(existing)); marked && m.Generator == "client" {
		return plan, true, nil
	}
	plan.owned = fileEdited(appClientPath, string(existing), plan.content)
	return plan, true, nil
}

// writeAppClient writes a planned client under dir.
func writeAppClient(dir string, plan appClientPlan) error {
	fileSet, err := fileSetFromGeneratedFiles([]generatedFile{{name: appClientPath, content: plan.content}}, "client")
	if err != nil {
		return err
	}
	return codegen.WriteFiles(fileSet, codegen.WriteOptions{OutputRoot: dir, SkipManifest: true, Conflict: codegen.ConflictOverwrite})
}

// runGenerateClient is `gofastr generate client`: rebuild entities/client
// from entities/. A client.go the app generator wrote and the user edited
// is theirs until --force says otherwise.
func runGenerateClient(args []string) {
	var force, dryRun, asJSON bool
	for _, a := range args {
		switch a {
		case "--force":
			force = true
		case "--dry-run":
			dryRun = true
		case "--json":
			asJSON = true
		default:
			fail("unknown flag: %s", a)
			info("Usage: gofastr generate client [--force] [--dry-run] [--json]")
			osExit(1)
			return
		}
	}
	failWith := func(err error) {
		if asJSON {
			printGeneratedErrorsJSON(err)
		} else {
			fail("%v", err)
		}
		osExit(1)
	}
	plan, ok, err := planAppClient(".")
	if err != nil {
		failWith(err)
		return
	}
	if !ok {
		failWith(fmt.Errorf("no entities package found in the current directory: run from your app root (the directory holding entities/)"))
		return
	}
	if plan.owned && !force {
		failWith(fmt.Errorf("%s was edited since `gofastr generate app` wrote it. It is now derived: every gofastr build rebuilds it from entities/ and would drop those edits. Move them into another file of package client, then run `gofastr generate client --force`", appClientPath))
		return
	}
	files := []generatedFile{{name: appClientPath, content: plan.content}}
	if dryRun {
		if asJSON {
			printGeneratedFilesJSON(files)
			return
		}
		info("Would write %s", appClientPath)
		return
	}
	if plan.owned && !asJSON {
		warnForceOverwrite([]string{appClientPath})
	} else if existing, rerr := readFileUnder(".", appClientPath); rerr == nil && !asJSON {
		warnDerivedEdit("client", appClientPath, string(existing), "the entity declarations in entities/")
	}
	if err := writeAppClient(".", plan); err != nil {
		failWith(fmt.Errorf("write %s: %w", appClientPath, err))
		return
	}
	if asJSON {
		printGeneratedFilesJSON(files)
		return
	}
	success("Rebuilt %s", appClientPath)
}

// refreshAppClient is the rebuild plain `gofastr generate`, `gofastr
// build` and `generate app --add` run: only when dir already has
// entities/client/client.go, never creating one, and never over an edited
// scaffold copy. That copy gets a warning naming the one command that
// takes it over. quiet drops the progress lines, for --json runs whose
// stdout is a document. It returns the file it wrote, or would write under
// dryRun.
func refreshAppClient(dir string, dryRun, quiet bool) ([]generatedFile, error) {
	say := warn
	note := info
	if quiet {
		say = func(string, ...any) {}
		note = say
	}
	if !appClientPresent(dir) {
		return nil, nil
	}
	plan, ok, err := planAppClient(dir)
	if err != nil || !ok {
		return nil, err
	}
	if plan.owned {
		say("%s was edited since `gofastr generate app` wrote it, so this run leaves it alone and it no longer tracks entities/. Move your edits into another file of package client, then run `gofastr generate client --force` once; builds keep it current from then on.", filepath.Join(dir, appClientPath))
		return nil, nil
	}
	if plan.unchanged {
		return nil, nil
	}
	files := []generatedFile{{name: appClientPath, content: plan.content}}
	if dryRun {
		note("Would rebuild %s", filepath.Join(dir, appClientPath))
		return files, nil
	}
	if !quiet {
		if existing, err := readFileUnder(dir, appClientPath); err == nil {
			warnDerivedEdit("client", appClientPath, string(existing), "the entity declarations in entities/")
		}
	}
	if err := writeAppClient(dir, plan); err != nil {
		return nil, fmt.Errorf("write %s: %w", appClientPath, err)
	}
	note("Rebuilt %s", filepath.Join(dir, appClientPath))
	return files, nil
}

// appClientPresent reports whether dir holds entities/client/client.go.
func appClientPresent(dir string) bool {
	return fileExistsUnder(dir, appClientPath)
}
