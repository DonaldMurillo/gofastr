// emitThemeGoSource renders t as a complete, gofmt'd theme.go source file
// the user owns forever, the same shape `gofastr theme init` writes, but
// with the edited values.
//
// # Security: every string value is emitted with %q
//
// Theme values are free-form CSS: oklch() expressions, font stacks with
// embedded quotes, shadow lists. A raw backtick literal has no escape
// mechanism, so a single backtick in a value closes it: the same class
// of injection blueprint_emitter_injection_test.go pins for the IR
// emitters. %q produces a Go double-quoted literal that escapes every
// breaking byte (backtick, quote, newline, backslash), so no theme
// value can leave its literal and become syntax. The companion
// TestThemeEditWritebackInjectionSafety drives literal-breaking payloads
// through this emitter and asserts they stay data.
//
// Names are intentionally omitted from every token field: the file ends
// with `func init() { style.AutoFillNames(&App) }`, which derives every
// Name from the Go struct-field path, the same contract `gofastr theme
// init` ships. Emitting Names here would only duplicate what AutoFillNames
// already produces and give a malicious value one more surface to reach.
func emitThemeGoSource(t style.Theme, pkgName string) ([]byte, error) {
	if pkgName == "" {
		pkgName = "theme"
	}
	var b strings.Builder
	b.WriteString("// Package " + pkgName + " defines this app's typed design system.\n")
	b.WriteString("//\n")
	b.WriteString("// Generated by `gofastr theme edit`. Edit values to customise the\n")
	b.WriteString("// brand; the framework never regenerates this file. Token names\n")
	b.WriteString("// auto-derive from struct field paths via style.AutoFillNames.\n")
	b.WriteString("package " + pkgName + "\n\n")
	b.WriteString("import (\n")
	b.WriteString("\t\"time\"\n")
	b.WriteString("\n")
	b.WriteString("\t\"github.com/DonaldMurillo/gofastr/core-ui/style\"\n")
	b.WriteString(")\n\n")
	b.WriteString("// App is this app's design system. Pass it to the host:\n")
	b.WriteString("//\n")
	b.WriteString("//\tapp.WithTheme(theme.App)\n")
	b.WriteString("var App = style.Theme{\n")
	fmt.Fprintf(&b, "\tName: %q,\n", t.Name)

	// DarkColors: sorted for byte-stable output.
	b.WriteString("\tDarkColors: map[string]string{\n")
	for _, k := range sortedStringKeys(t.DarkColors) {
		fmt.Fprintf(&b, "\t\t%q: %q,\n", k, t.DarkColors[k])
	}
	b.WriteString("\t},\n")

	// DarkCode: only emitted when non-empty (the optional code palette).
	if len(t.DarkCode) > 0 {
		b.WriteString("\tDarkCode: map[string]string{\n")
		for _, k := range sortedStringKeys(t.DarkCode) {
			fmt.Fprintf(&b, "\t\t%q: %q,\n", k, t.DarkCode[k])
		}
		b.WriteString("\t},\n")
	}

	emitColorSet(&b, &t.Colors)
	emitSpacingScale(&b, &t.Spacing)
	emitRadiusSet(&b, &t.Radii)
	emitFontSet(&b, &t.Fonts)
	emitBreakpointSet(&b, &t.Breakpoints)
	emitShadowSet(&b, &t.Shadows)
	emitZIndexSet(&b, &t.ZIndex)
	emitDurationSet(&b, &t.Durations)
	emitEasingSet(&b, &t.Easings)
	emitFontSizeSet(&b, &t.Typography)
	emitLayoutSet(&b, &t.Layout)
	emitCodeSet(&b, &t.Code)

	b.WriteString("}\n\n")
	b.WriteString("// init fills in token Names from struct-field paths. After this\n")
	b.WriteString("// runs, theme.App.Colors.Primary.Name == \"primary\".\n")
	b.WriteString("func init() {\n")
	b.WriteString("\tstyle.AutoFillNames(&App)\n")
	b.WriteString("}\n")

	formatted, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("theme edit: generated source does not parse: %w\n--- source ---\n%s", err, b.String())
	}
	return formatted, nil
}

