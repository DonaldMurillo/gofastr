// sortedStringKeys returns the keys of m in sorted order, or nil for an
// empty/nil map. Used so the emitted DarkColors/DarkCode blocks are
// byte-stable across runs.
func sortedStringKeys(m map[string]string) []string {
	if len(m) == 0 {
		return nil
	}
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

// packageNameForPath adopts the package clause from another Go file in the
// destination directory. A new directory falls back to its sanitized basename.
func packageNameForPath(p string) string {
	dir := filepath.Dir(p)
	entries, err := os.ReadDir(dir)
	if err == nil {
		target := filepath.Base(p)
		for _, includeTests := range []bool{false, true} {
			for _, entry := range entries {
				name := entry.Name()
				if entry.IsDir() || name == target || !strings.HasSuffix(name, ".go") {
					continue
				}
				isTest := strings.HasSuffix(name, "_test.go")
				if isTest != includeTests {
					continue
				}
				file, err := parser.ParseFile(token.NewFileSet(), filepath.Join(dir, name), nil, parser.PackageClauseOnly)
				if err != nil || file.Name == nil {
					continue
				}
				pkg := file.Name.Name
				if isTest {
					pkg = strings.TrimSuffix(pkg, "_test")
				}
				return pkg
			}
		}
	}

	name := filepath.Base(dir)
	if name == "." || name == string(filepath.Separator) || name == "" {
		return "theme"
	}
	return sanitizePackageName(name)
}

// sanitizePackageName turns a directory name into a legal Go package clause.
//
// The package clause is the ONE string in the emitted file that does not go
// through %q, because it is an identifier rather than a literal. A directory
// called "design-system" therefore produced `package design-system`, which does
// not parse, so Write failed on every attempt with a 500 carrying the whole
// generated file, and nothing was ever written. Same for a leading digit, a
// dot, or a Go keyword.
func sanitizePackageName(name string) string {
	var b strings.Builder
	for _, r := range name {
		switch {
		case r >= 'a' && r <= 'z', r >= 'A' && r <= 'Z', r >= '0' && r <= '9':
			b.WriteRune(r)
		case r == '_':
			b.WriteRune(r)
		default:
			// '-', '.', ' ' and friends become '_' rather than vanishing, so
			// "design-system" reads as "design_system" instead of
			// "designsystem".
			b.WriteRune('_')
		}
	}
	out := b.String()
	out = strings.Trim(out, "_")
	if out == "" {
		return "theme"
	}
	if out[0] >= '0' && out[0] <= '9' {
		out = "_" + out
	}
	if token.Lookup(out).IsKeyword() {
		out += "_"
	}
	return out
}
