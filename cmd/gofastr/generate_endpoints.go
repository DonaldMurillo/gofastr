// appEndpointsPath is where the endpoints generator writes the registration
// of the settings endpoints, relative to the app root.
const appEndpointsPath = "entities/endpoints.gen.go"

// schemaTypeNames spells each type an endpoint input can have as the
// core/schema constant.
var schemaTypeNames = map[schema.FieldType]string{
	schema.String: "schema.String", schema.Int: "schema.Int", schema.Float: "schema.Float",
	schema.Bool: "schema.Bool", schema.Timestamp: "schema.Timestamp", schema.JSON: "schema.JSON",
}

// renderAppEndpoints renders entities/endpoints.gen.go: one
// App.EntityEndpoints call per endpoint, from a registrar ordered before
// every entity so each endpoint joins its entity's registration.
func renderAppEndpoints(eps []appEndpoint) (string, error) {
	var body strings.Builder
	usesSchema := false
	for _, ep := range eps {
		fmt.Fprintf(&body, "\tapp.EntityEndpoints(%q, framework.Endpoint{\n", ep.Entity)
		fmt.Fprintf(&body, "\t\tName:   %q,\n\t\tMethod: %q,\n\t\tPath:   %q,\n", ep.Name, ep.Method, ep.Path)
		if ep.Description != "" {
			fmt.Fprintf(&body, "\t\tDescription: %q,\n", ep.Description)
		}
		if ep.MCP {
			body.WriteString("\t\tMCP: true,\n")
		}
		if ep.Public {
			body.WriteString("\t\tPublic: true,\n")
		}
		body.WriteString("\t\tSDK: true,\n")
		if ep.returns != "" {
			fmt.Fprintf(&body, "\t\tReturns: %q,\n", ep.returns)
		}
		if len(ep.params) > 0 {
			usesSchema = true
			body.WriteString("\t\tInputSchema: []schema.Field{\n")
			for _, p := range ep.params {
				fmt.Fprintf(&body, "\t\t\t{Name: %q, Type: %s, Required: %t},\n", p.name, schemaTypeNames[p.typ], p.required)
			}
			body.WriteString("\t\t},\n")
		}
		typeArgs := ep.input + ", " + ep.output
		fmt.Fprintf(&body, "\t\tHandler: handler.HandlerAdapter[%s](%s),\n", typeArgs, ep.HandlerName())
		if ep.MCP {
			fmt.Fprintf(&body, "\t\tMCPHandler: handler.ToolAdapter[%s](%s),\n", typeArgs, ep.HandlerName())
		}
		body.WriteString("\t})\n")
	}
	var sb strings.Builder
	sb.WriteString("// Code generated by \"gofastr generate endpoints\" from gofastr.settings.yml. DO NOT EDIT.\n")
	sb.WriteString("// Change an endpoint under endpoints: in gofastr.settings.yml, or in its handler.\n\n")
	sb.WriteString("package entities\n\nimport (\n\t\"github.com/DonaldMurillo/gofastr/core/handler\"\n")
	if usesSchema {
		sb.WriteString("\t\"github.com/DonaldMurillo/gofastr/core/schema\"\n")
	}
	sb.WriteString("\t\"github.com/DonaldMurillo/gofastr/framework\"\n)\n\n")
	sb.WriteString("func init() {\n\tregistrars = append(registrars, registrar{order: -1, fn: registerEndpoints})\n}\n\n")
	sb.WriteString("// registerEndpoints queues the endpoints gofastr.settings.yml declares.\n")
	sb.WriteString("// Order -1 runs it before any entity registers, so each endpoint joins\n// its entity's registration.\n")
	sb.WriteString("func registerEndpoints(app *framework.App) {\n")
	sb.WriteString(body.String())
	sb.WriteString("}\n")
	return stampFile("endpoints", appEndpointsPath, sb.String())
}

// appEndpointsPlan is what an endpoints rebuild would do to the file.
type appEndpointsPlan struct {
	// content is the file to write; empty means the file should not exist.
	content string
	// existing is the file on disk, when there is one.
	existing string
	present  bool
}

func (p appEndpointsPlan) unchanged() bool {
	return p.content == p.existing && p.present == (p.content != "")
}

// planAppEndpoints renders the endpoints file for the app under dir.
// ok is false when dir has no entities package.
func planAppEndpoints(dir string) (plan appEndpointsPlan, ok bool, err error) {
	decls, err := packReadEntities(dir)
	if err != nil {
		return plan, false, fmt.Errorf("read entities: %w", err)
	}
	// An app with no entities yet has nothing to rebuild, unless the
	// settings declare endpoints: then the resolver names the missing
	// entity instead of the run passing in silence.
	if len(decls) == 0 && !appEndpointsWanted(dir) {
		return plan, false, nil
	}
	if existing, rerr := readFileUnder(dir, appEndpointsPath); rerr == nil {
		plan.existing, plan.present = string(existing), true
		if m, _, marked := codegen.ReadMarker(appEndpointsPath, plan.existing); !marked || m.Generator != "endpoints" {
			return plan, true, fmt.Errorf("%s exists and `gofastr generate endpoints` did not write it; rename it, since the endpoints generator owns that name", appEndpointsPath)
		}
	}
	eps, err := readAppEndpoints(dir, decls)
	if err != nil {
		return plan, true, err
	}
	if len(eps) == 0 {
		return plan, true, nil
	}
	src, err := readEntitiesSource(dir)
	if err != nil {
		return plan, true, err
	}
	if src.types["registrar"] == nil {
		return plan, true, fmt.Errorf("endpoints need the entities package `gofastr generate app` writes, whose register.go runs registrars; this one has none")
	}
	plan.content, err = renderAppEndpoints(eps)
	return plan, true, err
}

// refreshAppEndpoints is the endpoints rebuild every plain `gofastr
// generate` and `gofastr build` runs, and `gofastr generate endpoints`
// itself. It writes the file when the settings file declares endpoints and
// removes it when the section is gone. quiet drops the progress lines.
func refreshAppEndpoints(dir string, dryRun, quiet bool) ([]generatedFile, error) {
	note := info
	if quiet {
		note = func(string, ...any) {}
	}
	plan, ok, err := planAppEndpoints(dir)
	if err != nil || !ok || plan.unchanged() {
		return nil, err
	}
	display := filepath.Join(dir, appEndpointsPath)
	if plan.content == "" {
		if dryRun {
			note("Would remove %s: gofastr.settings.yml declares no endpoints", display)
			return nil, nil
		}
		root, err := os.OpenRoot(dir)
		if err != nil {
			return nil, err
		}
		defer root.Close()
		if err := root.Remove(appEndpointsPath); err != nil {
			return nil, fmt.Errorf("remove %s: %w", appEndpointsPath, err)
		}
		note("Removed %s: gofastr.settings.yml declares no endpoints", display)
		return nil, nil
	}
	files := []generatedFile{{name: appEndpointsPath, content: plan.content}}
	if dryRun {
		note("Would rebuild %s", display)
		return files, nil
	}
	if plan.present && !quiet {
		warnDerivedEdit("endpoints", appEndpointsPath, plan.existing, "the endpoints section of gofastr.settings.yml")
	}
	fileSet, err := fileSetFromGeneratedFiles(files, "endpoints")
	if err != nil {
		return nil, err
	}
	if err := codegen.WriteFiles(fileSet, codegen.WriteOptions{OutputRoot: dir, SkipManifest: true, Conflict: codegen.ConflictOverwrite}); err != nil {
		return nil, fmt.Errorf("write %s: %w", appEndpointsPath, err)
	}
	note("Rebuilt %s", display)
	return files, nil
}

// appEndpointsWanted reports whether dir's settings file declares endpoints
// or dir holds the endpoints file, so a plain generate has work to do.
func appEndpointsWanted(dir string) bool {
	if fileExistsUnder(dir, appEndpointsPath) {
		return true
	}
	f, err := settings.Load(filepath.Join(dir, settings.FileName))
	return err == nil && f.Section("endpoints") != nil
}

// runGenerateEndpoints is `gofastr generate endpoints`.
func runGenerateEndpoints(args []string) {
	var dryRun, asJSON bool
	for _, a := range args {
		switch a {
		case "--dry-run":
			dryRun = true
		case "--json":
			asJSON = true
		default:
			fail("unknown flag: %s", a)
			info("Usage: gofastr generate endpoints [--dry-run] [--json]")
			osExit(1)
			return
		}
	}
	if !fileExistsUnder(".", "entities") {
		fail("no entities package found in the current directory: run from your app root (the directory holding entities/)")
		osExit(1)
		return
	}
	files, err := refreshAppEndpoints(".", dryRun, asJSON)
	if err != nil {
		if asJSON {
			printGeneratedErrorsJSON(err)
		} else {
			fail("%v", err)
		}
		osExit(1)
		return
	}
	if asJSON {
		printGeneratedFilesJSON(files)
	}
}
