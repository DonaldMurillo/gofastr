func removeRetiredAppSpecFiles(writeRoot string) error {
	for _, name := range []string{"resource_test.go"} {
		content, err := readFileUnder(writeRoot, name)
		if err != nil {
			if os.IsNotExist(err) {
				continue
			}
			return err
		}
		if !strings.Contains(string(content), "Code generated by gofastr.") {
			continue
		}
		if err := os.Remove(filepath.Join(writeRoot, name)); err != nil && !os.IsNotExist(err) {
			return err
		}
	}
	return nil
}

func reportCodegenDiagnostics(diags []codegen.Diagnostic, jsonMode ...bool) bool {
	failed := false
	output := os.Stdout
	if len(jsonMode) > 0 && jsonMode[0] {
		output = os.Stderr
	}
	for _, d := range diags {
		message := d.Message
		switch asciicase.Lower(strings.TrimSpace(d.Severity)) {
		case "error":
			cli.Fprintf(output, "  ✗ %s\n", message)
			failed = true
		case "warning", "warn":
			cli.Fprintf(output, "  ⚠ %s\n", message)
		default:
			cli.Fprintf(output, "  → %s\n", message)
		}
	}
	if failed {
		cli.Fprintf(output, "  ✗ Code generation failed: an extension reported an error diagnostic\n")
	}
	return failed
}

// FormatGenerated gofmts a generated Go file, returning it unchanged when it does not parse.
func FormatGenerated(name, content string) string {
	if !strings.HasSuffix(name, ".go") {
		return content
	}
	if formatted, err := format.Source([]byte(content)); err == nil {
		return string(formatted)
	}
	return content
}

func FileSetFromGeneratedFiles(files []GeneratedFile, owner string) (*codegen.FileSet, error) {
	fileSet := codegen.NewFileSet()
	for _, file := range files {
		content := FormatGenerated(file.Name, file.Content)
		if err := fileSet.Add(codegen.GeneratedFile{Path: file.Name, Content: content, Owner: owner, Mode: file.Mode}); err != nil {
			return nil, err
		}
	}
	return fileSet, nil
}

func editedTargets(files []GeneratedFile, writeRoot, outDir string) []string {
	var edited []string
	for _, file := range files {
		existing, err := readFileUnder(writeRoot, file.Name)
		if err != nil {
			continue
		}
		if fileEdited(file.Name, string(existing), file.Content) {
			edited = append(edited, filepath.Join(outDir, file.Name))
		}
	}
	sort.Strings(edited)
	return edited
}

func validateOutputDir(dir string) error {
	if strings.TrimSpace(dir) == "" {
		return fmt.Errorf("--out must not be empty")
	}
	clean := filepath.Clean(dir)
	if filepath.IsAbs(clean) {
		return fmt.Errorf("--out must be a relative path inside the project (got %q)", dir)
	}
	if clean == "." || clean == ".." {
		return fmt.Errorf("--out=%q would target the working directory; choose a subdirectory like gen/entities", dir)
	}
	for _, part := range strings.Split(clean, string(filepath.Separator)) {
		if part == ".." {
			return fmt.Errorf("--out=%q must not contain parent directory traversal", dir)
		}
	}
	return nil
}

func safeCleanOutputDir(dir string) error {
	if err := codegen.EnsureNoSymlinkPath(dir); err != nil {
		return err
	}
	info, err := os.Stat(dir)
	if err != nil {
		if os.IsNotExist(err) {
			return nil
		}
		return err
	}
	if !info.IsDir() {
		return fmt.Errorf("%s exists and is not a directory", dir)
	}
	entries, err := os.ReadDir(dir)
	if err != nil {
		return err
	}
	owned := map[string]bool{
		".gitkeep": true, codegen.ManifestName: true,
		"main.go": true, "app.go": true, "screens.go": true, "stubs.go": true,
		"resource.go": true, "resource_test.go": true, "e2e_test.go": true,
		".env": true, ".gitignore": true,
		"register.go": true, "models.go": true, "columns.go": true, "repo.go": true, "events.go": true,
		"client": true, "entities": true, "blueprint": true,
	}
	for _, entry := range entries {
		if !owned[entry.Name()] {
			return fmt.Errorf("refusing to clean %s: contains unknown entry %q (move it or use --no-clean)", dir, entry.Name())
		}
	}
	for name := range owned {
		path := filepath.Join(dir, name)
		if name == ".gitkeep" {
			continue
		}
		if err := codegen.EnsureNoSymlinkPath(filepath.Dir(path)); err != nil {
			return err
		}
		if err := os.RemoveAll(path); err != nil && !os.IsNotExist(err) {
			return err
		}
	}
	return nil
}

func withoutNames(names, drop []string) []string {
	return slices.DeleteFunc(names, func(n string) bool { return slices.Contains(drop, n) })
}

func entityFileName(name string) string {
	snake := appspec.ToSnakeCase(name)
	switch snake {
	case "register", "events", "shared", "doc":
		return "entity_" + snake + ".go"
	}
	return snake + ".go"
}

func fileExistsUnder(writeRoot, rel string) bool {
	root, err := os.OpenRoot(writeRoot)
	if err != nil {
		return false
	}
	defer root.Close()
	_, err = root.Stat(rel)
	return err == nil
}

func addScreenTarget(writeRoot string, s appspec.AppSpecScreen) (file string, declared, dropped bool) {
	entity, crud := appspec.ScreenEntityRef(s)
	if !crud {
		file = appspec.ScreenFileName(s.Name)
		return file, fileExistsUnder(writeRoot, file), false
	}
	file = appspec.ScreenFileName(entity + "_crud")
	src, err := readFileUnder(writeRoot, file)
	if err != nil {
		return file, false, false
	}
	declared = strings.Contains(string(src), "func mount"+appspec.ToCamelCase(s.Name)+"Screen(")
	return file, declared, !declared
}

func checkAddScreenInvalidation(writeRoot string, written []GeneratedFile, skipped []string) error {
	const register = "screens_register.go"
	const helper = "invalidateScreensOnWrite"
	if !slices.Contains(skipped, register) {
		return nil
	}
	dependent := slices.IndexFunc(written, func(f GeneratedFile) bool {
		return IsPerScreenSource(f.Name) && strings.Contains(f.Content, "\t"+helper+"(fwApp, ")
	})
	if dependent < 0 {
		return nil
	}
	if slices.Contains(packageNamesUnder(writeRoot), helper) {
		return nil
	}
	return fmt.Errorf("--add cannot write %s: %s lacks %s. Generate the full app in a scratch directory and copy the helper and its imports into %s, then retry --add",
		written[dependent].Name, register, helper, register)
}

func checkAddScreenShell(writeRoot string, written []GeneratedFile) error {
	if !fileExistsUnder(writeRoot, "app.go") {
		return nil
	}
	declared := packageNamesUnder(writeRoot)
	for _, f := range written {
		if !IsPerScreenSource(f.Name) {
			continue
		}
		file, err := parser.ParseFile(token.NewFileSet(), f.Name, f.Content, parser.SkipObjectResolution)
		if err != nil {
			continue
		}
		missing := ""
		ast.Inspect(file, func(n ast.Node) bool {
			if id, ok := n.(*ast.Ident); ok && missing == "" && (id.Name == "authPolicy" || id.Name == "marketingLayout") && !slices.Contains(declared, id.Name) {
				missing = id.Name
			}
			return missing == ""
		})
		if missing != "" {
			return fmt.Errorf("--add cannot write %s: it mounts through %s, which no Go file in the project declares (a generated app.go declares it only when the app spec already has a gated or marketing screen, and --add does not edit app.go). Generate the app spec with the screen in it into a scratch directory and copy %s and its imports from that app.go into yours, then retry --add", f.Name, missing, missing)
		}
	}
	return nil
}

func readFileUnder(writeRoot, rel string) ([]byte, error) {
	root, err := os.OpenRoot(writeRoot)
	if err != nil {
		return nil, err
	}
	defer root.Close()
	return root.ReadFile(rel)
}

func projectPhraseApp(writeRoot string) string {
	root, err := os.OpenRoot(writeRoot)
	if err != nil {
		return ""
	}
	defer root.Close()
	entries, err := RootReadDirEntries(root, ".")
	if err != nil {
		return ""
	}
	slices.SortFunc(entries, func(a, b os.DirEntry) int { return strings.Compare(a.Name(), b.Name()) })
	appName := ""
	for _, entry := range entries {
		name := entry.Name()
		if entry.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") {
			continue
		}
		src, rerr := root.ReadFile(name)
		if rerr != nil {
			continue
		}
		file, perr := parser.ParseFile(token.NewFileSet(), name, src, 0)
		if perr != nil {
			continue
		}
		ns := ""
		ast.Inspect(file, func(n ast.Node) bool {
			if ns != "" {
				return false
			}
			call, ok := n.(*ast.CallExpr)
			if !ok || len(call.Args) != 2 {
				return true
			}
			if sel, ok := call.Fun.(*ast.SelectorExpr); !ok || sel.Sel.Name != "Define" || IdentName(sel.X) != "i18n" {
				return true
			}
			parts := strings.SplitN(appspec.AstString(call.Args[0]), ".", 3)
			if len(parts) == 3 && parts[0] != "" && (parts[1] == "screens" || parts[1] == "chrome") {
				ns = parts[0]
			}
			return ns == ""
		})
		if ns != "" {
			return ns
		}
		if name == "app.go" {
			for _, d := range file.Decls {
				gd, ok := d.(*ast.GenDecl)
				if !ok || gd.Tok != token.CONST {
					continue
				}
				for _, spec := range gd.Specs {
					if vs, ok := spec.(*ast.ValueSpec); ok && len(vs.Names) == 1 && vs.Names[0].Name == "appName" && len(vs.Values) == 1 {
						appName = appspec.AstString(vs.Values[0])
					}
				}
			}
		}
	}
	return appName
}

