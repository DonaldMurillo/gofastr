// cliCustomFile is the CLI's one owned file: created when absent, never
// rewritten.
const cliCustomFile = "custom.go"

// cliCustomBackup is where --force moves a custom.go written for the other
// generation mode.
const cliCustomBackup = cliCustomFile + ".bak"

// otherCLIClientImport is the client package the other generation mode
// imports: the entity SDK (<base>/entities/client) for an --from-openapi
// run, the CLI's own internal/client for an entity run.
func otherCLIClientImport(outDir string, spec cliSpec) string {
	// Spelled the way runGenerateCLIFromOpenAPI builds it, uncleaned.
	self := "/" + filepath.ToSlash(outDir) + "/internal/client"
	if spec.SelfClient {
		return strings.TrimSuffix(spec.ClientImport, self) + "/entities/client"
	}
	return strings.TrimSuffix(spec.ClientImport, "/entities/client") + self
}

// staleCustomClient returns the other mode's client package when the
// custom.go under outDir imports it: the file was written for the other
// generation mode and no longer builds beside this run's files. It returns
// "" when custom.go is absent, does not parse, or imports no such package.
func staleCustomClient(outDir, relOut string, spec cliSpec) string {
	data, err := readFileUnder(outDir, cliCustomFile)
	if err != nil {
		return ""
	}
	f, err := parser.ParseFile(token.NewFileSet(), cliCustomFile, data, parser.ImportsOnly)
	if err != nil {
		return ""
	}
	other := otherCLIClientImport(relOut, spec)
	for _, imp := range f.Imports {
		if p, err := strconv.Unquote(imp.Path.Value); err == nil && p == other {
			return p
		}
	}
	return ""
}

// backupCLICustom renames custom.go to custom.go.bak under outDir. The
// rename goes through an *os.Root so neither name resolves out of the
// directory, and it refuses to replace a backup that appeared since the
// run checked.
func backupCLICustom(outDir string) error {
	root, err := os.OpenRoot(outDir)
	if err != nil {
		return err
	}
	defer root.Close()
	if _, err := root.Lstat(cliCustomBackup); err == nil {
		return fmt.Errorf("%s already exists; move or delete it, then re-run", path.Join(outDir, cliCustomBackup))
	}
	if err := root.Rename(cliCustomFile, cliCustomBackup); err != nil {
		return fmt.Errorf("move %s to %s: %w", cliCustomFile, cliCustomBackup, err)
	}
	return nil
}

// cliGeneratedLine heads every derived CLI file, the line go tooling reads
// to treat a file as generated.
const cliGeneratedLine = "// Code generated by \"gofastr generate cli\". DO NOT EDIT.\n\n"

// cliSourceName names what a derived CLI file is rebuilt from, for the
// edit warning.
func cliSourceName(spec cliSpec) string {
	if len(spec.Ops) > 0 {
		return "the OpenAPI document"
	}
	return "the entity declarations in entities/"
}

// stampCLIFiles stamps the rendered CLI: custom.go as a scaffold file the
// user owns, the rest as the cli generator's derived output. stampFile
// keeps a marker that is already there, so custom.go is stamped first.
func stampCLIFiles(files []GeneratedFile) ([]GeneratedFile, error) {
	out := make([]GeneratedFile, len(files))
	copy(out, files)
	for i, f := range out {
		if f.Name != cliCustomFile {
			continue
		}
		content, err := codegen.Stamp(f.Name, FormatGenerated(f.Name, f.Content), codegen.Marker{
			Generator: "cli",
			Kind:      codegen.KindScaffold,
			Version:   MarkerVersion(project.CliVersion()),
		})
		if err != nil {
			return nil, err
		}
		out[i].Content = content
	}
	return StampGeneratedFiles("cli", out)
}

// cliRemoval is a file in the CLI directory that this run deletes.
type cliRemoval struct {
	name string
	// legacy: a file from before the CLI was derived (main.go, posts.go,
	// ...), which a *.gen.go file now replaces.
	legacy bool
	// edited: the file holds changes since it was generated, or carries no
	// marker to tell.
	edited bool
}

// cliGenDirs are the directories the CLI generator writes into, relative
// to its output directory. Removal looks nowhere else.
var cliGenDirs = []string{".", "internal/client"}

// planCLIRemovals lists the files under outDir the new render replaces or
// no longer produces: derived files carrying the cli marker that are not in
// files, and the pre-derived layout's files (a cli scaffold marker, or no
// marker and the name a *.gen.go file now takes). Anything else in the
// directory is the user's and stays.
func planCLIRemovals(outDir string, files []GeneratedFile) ([]cliRemoval, error) {
	root, err := os.OpenRoot(outDir)
	if err != nil {
		if os.IsNotExist(err) {
			return nil, nil
		}
		return nil, err
	}
	defer root.Close()
	keep := map[string]bool{cliCustomFile: true}
	legacyNames := map[string]bool{}
	for _, f := range files {
		keep[f.Name] = true
		if strings.HasSuffix(f.Name, ".gen.go") {
			legacyNames[strings.TrimSuffix(f.Name, ".gen.go")+".go"] = true
		}
	}
	var out []cliRemoval
	for _, dir := range cliGenDirs {
		// A symlinked directory would list files a second time under
		// another name, none of them in keep: removing those deletes what
		// this run just wrote, custom.go included. os.Root only stops an
		// escape, not an alias inside the root.
		if dir != "." {
			if info, err := root.Lstat(dir); err == nil && info.Mode()&fs.ModeSymlink != 0 {
				return nil, fmt.Errorf("%s is a symlink; the CLI generator writes and cleans real directories only", path.Join(outDir, dir))
			}
		}
		entries, err := fs.ReadDir(root.FS(), dir)
		if err != nil {
			continue
		}
		for _, e := range entries {
			name := path.Join(dir, e.Name())
			if !e.Type().IsRegular() || !strings.HasSuffix(name, ".go") || keep[name] {
				continue
			}
			data, err := root.ReadFile(name)
			if err != nil {
				return nil, fmt.Errorf("read %s: %w", name, err)
			}
			m, body, marked := codegen.ReadMarker(name, string(data))
			switch {
			case marked && m.Generator == "cli" && m.Kind == codegen.KindDerived:
				out = append(out, cliRemoval{name: name, edited: codegen.Sum(body) != m.Sum})
			case marked && m.Generator == "cli":
				out = append(out, cliRemoval{name: name, legacy: true, edited: codegen.Sum(body) != m.Sum})
			case !marked && legacyNames[name]:
				out = append(out, cliRemoval{name: name, legacy: true, edited: true})
			}
		}
	}
	return out, nil
}

// removeCLIFiles deletes the planned files through an os.Root, so a
// symlinked entry cannot point the delete outside the CLI directory.
func removeCLIFiles(outDir string, removals []cliRemoval) error {
	if len(removals) == 0 {
		return nil
	}
	root, err := os.OpenRoot(outDir)
	if err != nil {
		return err
	}
	defer root.Close()
	for _, r := range removals {
		if err := root.Remove(r.name); err != nil && !os.IsNotExist(err) {
			return fmt.Errorf("remove %s: %w", r.name, err)
		}
	}
	return nil
}

// dropUnchangedFiles returns the files whose content differs from what is
// on disk under dir, so a rebuild rewrites only what moved.
func dropUnchangedFiles(dir string, files []GeneratedFile) []GeneratedFile {
	var out []GeneratedFile
	for _, f := range files {
		if existing, err := readFileUnder(dir, f.Name); err == nil && string(existing) == f.Content {
			continue
		}
		out = append(out, f)
	}
	return out
}
