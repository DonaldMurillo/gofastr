// Header returns the DO-NOT-EDIT stamp of every generated SDK file, its values made inert in every comment syntax.
func (s sdkSpec) Header() string {
	return fmt.Sprintf("Code generated by gofastr %s (sdk %s) for %s. DO NOT EDIT.",
		sdkCommentSafe(s.GofastrVersion), sdkCommentSafe(s.SDKVersion), sdkCommentSafe(s.App))
}

func sdkCommentSafe(value string) string {
	var b strings.Builder
	b.Grow(len(value))
	for _, r := range value {
		if r < 0x20 || r == 0x7f {
			continue
		}
		b.WriteRune(r)
	}
	out := b.String()
	out = strings.ReplaceAll(out, "-->", "- ->")
	return strings.ReplaceAll(out, "*/", "* /")
}

func sdkMarkdownSafe(value string) string {
	var b strings.Builder
	b.Grow(len(value))
	for _, r := range value {
		if r < 0x20 || r == 0x7f || r == '`' || r == '~' {
			continue
		}
		b.WriteRune(r)
	}
	out := b.String()
	out = strings.ReplaceAll(out, "-->", "- ->")
	return strings.ReplaceAll(out, "*/", "* /")
}

func sdkFenceWord(value string) string {
	var b strings.Builder
	b.Grow(len(value))
	for _, r := range value {
		switch {
		case r >= 'a' && r <= 'z', r >= 'A' && r <= 'Z', r >= '0' && r <= '9',
			r == '-', r == '_', r == '.', r == '~':
			b.WriteRune(r)
		}
	}
	return b.String()
}

var sdkModulePathRe = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9._~/-]*$`)

func validateSDKModulePath(module string) error {
	if !sdkModulePathRe.MatchString(module) {
		return fmt.Errorf("--module %q is not a usable Go module path. Use letters, digits, dot, dash, underscore, tilde and slash (e.g. example.com/app-sdk)", module)
	}
	if strings.Contains(module, "//") || strings.HasSuffix(module, "/") {
		return fmt.Errorf("--module %q is not a usable Go module path: empty path element", module)
	}
	return nil
}

var sdkValidTargets = map[string]bool{"go": true, "js": true}

const sdkDefaultOut = "gen/sdk"

// RunGenerateSDK implements `gofastr generate sdk`.
func RunGenerateSDK(args []string) {
	const usage = "Usage: gofastr generate sdk [--from-openapi=<path|url>] [--target=go,js] [--out=gen/sdk] [--name=<app>] [--api-prefix=api] [--only=a,b] [--exclude=c] [--module=<path>] [--base-url=<url>] [--sdk-version=<semver>] [--no-archive] [--stamp-time] [--dry-run] [--json]"
	if showGenerateHelp(args, usage) {
		return
	}
	opts, err := parseSDKOptions(args)
	if err != nil {
		failGenerateArgs(args, err, usage)
		cli.OsExit(2)
		return
	}
	if err := ApplySDKConfigDefaults(&opts); err != nil {
		failGenerate(opts.json, err)
		cli.OsExit(1)
		return
	}

	if opts.fromOpenAPI != "" {
		root := ""
		if !opts.set["from-openapi"] {
			root = "."
		}
		files, err := renderOpenAPISDK(&opts, root)
		if err != nil {
			failGenerate(opts.json, fmt.Errorf("SDK generation failed: %s", textsafe.ScrubControlBytes(err.Error())))
			cli.OsExit(1)
			return
		}
		if err := validateOutputDir(opts.OutDir); err != nil {
			failGenerate(opts.json, err)
			cli.OsExit(1)
			return
		}
		emitSDKFiles(opts, files, "the OpenAPI document")
		return
	}

	decls, err := ReadAppDecls(".")
	if err != nil {
		failGenerate(opts.json, fmt.Errorf("read entities: %v", err))
		cli.OsExit(1)
		return
	}
	if len(decls) == 0 {
		failGenerate(opts.json, fmt.Errorf("no entities package found in the current directory"))
		cli.Fprintln(os.Stderr, "Run from your app root (the directory holding entities/), or generate the app first: gofastr generate app <spec.yml>.")
		cli.OsExit(1)
		return
	}

	spec, err := buildSDKSpec(decls, &opts)
	if err != nil {
		failGenerate(opts.json, err)
		cli.OsExit(1)
		return
	}
	if err := validateOutputDir(opts.OutDir); err != nil {
		failGenerate(opts.json, err)
		cli.OsExit(1)
		return
	}

	files, err := renderSDKFiles(spec, opts.targets, !opts.noArchive)
	if err != nil {
		failGenerate(opts.json, fmt.Errorf("SDK generation failed: %v", err))
		cli.OsExit(1)
		return
	}
	emitSDKFiles(opts, files, "the entity declarations")
}

func emitSDKFiles(opts SdkOptions, files []GeneratedFile, source string) {
	if opts.dryRun {
		if opts.json {
			printGeneratedFilesJSON(files)
			return
		}
		cli.Info("Would generate %d file(s) in %s:", len(files), opts.OutDir)
		for _, f := range files {
			cli.Printf("    %s\n", filepath.Join(opts.OutDir, f.Name))
		}
		return
	}

	if !opts.json {
		for _, f := range files {
			if existing, rerr := readFileUnder(opts.OutDir, f.Name); rerr == nil {
				warnDerivedEdit("sdk", filepath.Join(opts.OutDir, f.Name), string(existing), source)
			}
		}
	}
	fileSet, err := FileSetFromGeneratedFiles(files, "sdk")
	if err != nil {
		failGenerate(opts.json, fmt.Errorf("SDK generation failed: %v", err))
		cli.OsExit(1)
		return
	}
	writeOpts := codegen.WriteOptions{
		OutputRoot:   opts.OutDir,
		SkipManifest: true,
		Conflict:     codegen.ConflictOverwrite,
	}
	if err := codegen.WriteFiles(fileSet, writeOpts); err != nil {
		failGenerate(opts.json, fmt.Errorf("Failed to write generated files: %v", err))
		cli.OsExit(1)
		return
	}
	if opts.json {
		printGeneratedFilesJSON(files)
		return
	}
	cli.Success("Generated %d file(s) in %s", len(files), opts.OutDir)
	fmt.Println()
	fmt.Println("  Next steps:")
	dist := filepath.ToSlash(filepath.Join(opts.OutDir, "dist"))
	if opts.fromOpenAPI != "" {
		cli.Printf("    serve the downloads: sdkdocs.Mount(site, app.Router(), sdkdocs.Config{Registry: app.Registry, Artifacts: os.DirFS(%q), OpenAPI: <the document's JSON>})\n", dist)
		fmt.Println("    re-run this command whenever the OpenAPI document changes: output regenerates in place")
		return
	}
	cli.Printf("    serve the downloads: sdkdocs.Mount(site, app.Router(), sdkdocs.Config{Registry: app.Registry, Artifacts: os.DirFS(%q)})\n", dist)
	fmt.Println("    re-run this command whenever entities change: output regenerates in place")
}

func parseSDKOptions(args []string) (SdkOptions, error) {
	opts := SdkOptions{set: map[string]bool{}}
	var flagErr error
	for i := 0; i < len(args); i++ {
		arg := args[i]
		nextValue := func() (string, bool) {
			if i+1 < len(args) && !cli.IsFlagToken(args[i+1]) {
				i++
				return args[i], true
			}
			flagErr = cli.NeedsValue(arg)
			return "", false
		}
		value := func(prefix string) (string, bool) {
			if strings.HasPrefix(arg, prefix+"=") {
				return strings.TrimPrefix(arg, prefix+"="), true
			}
			if arg == prefix {
				return nextValue()
			}
			return "", false
		}
		switch {
		case arg == "--no-archive":
			opts.noArchive = true
		case arg == "--stamp-time":
			opts.stampTime = true
		case arg == "--dry-run":
			opts.dryRun = true
		case arg == "--json":
			opts.json = true
		default:
			if v, ok := value("--out"); ok {
				opts.OutDir = v
			} else if v, ok := value("--name"); ok {
				opts.name = v
			} else if v, ok := value("--api-prefix"); ok {
				opts.apiPrefix = v
			} else if v, ok := value("--module"); ok {
				opts.module = v
			} else if v, ok := value("--base-url"); ok {
				opts.baseURL = v
			} else if v, ok := value("--sdk-version"); ok {
				opts.sdkVersion = v
			} else if v, ok := value("--target"); ok {
				opts.targets = splitCommaList(v)
			} else if v, ok := value("--from-openapi"); ok {
				opts.fromOpenAPI = v
			} else if v, ok := value("--only"); ok {
				opts.only = splitCommaList(v)
			} else if v, ok := value("--exclude"); ok {
				opts.exclude = splitCommaList(v)
			} else if flagErr != nil {
				return opts, flagErr
			} else {
				return opts, fmt.Errorf("unknown flag: %s", arg)
			}
			flag, _, _ := strings.Cut(strings.TrimPrefix(arg, "--"), "=")
			opts.set[flag] = true
		}
	}
	for _, t := range opts.targets {
		if !sdkValidTargets[t] {
			return opts, fmt.Errorf("--target: unknown target %q (valid: go, js)", t)
		}
	}
	return opts, nil
}

// ApplySDKConfigDefaults fills unset options from the project's sdk settings entry; flags always win.
func ApplySDKConfigDefaults(opts *SdkOptions) error {
	if err := applySDKConfigDefaults(opts); err != nil {
		return err
	}
	if opts.fromOpenAPI != "" {
		return checkOpenAPISDKOptions(*opts)
	}
	return applySDKAppDefaults(".", opts)
}

func applySDKAppDefaults(dir string, opts *SdkOptions) error {
	if opts.apiPrefix != "" || opts.set["api-prefix"] {
		return nil
	}
	var found []string
	for _, name := range appspec.RootFileNames {
		path := filepath.Join(dir, name)
		if _, err := os.Stat(path); os.IsNotExist(err) {
			continue
		} else if err != nil {
			return err
		}
		found = append(found, name)
	}
	switch len(found) {
	case 0:
		return nil
	case 1:
	default:
		return fmt.Errorf("found %s: cannot tell which spec sets the API prefix; pass --api-prefix or set api_prefix on the sdk generator in gofastr.settings.yml", strings.Join(found, " and "))
	}
	spec, err := appspec.DecodeAppSpecFile(filepath.Join(dir, found[0]))
	if err != nil {
		return err
	}
	opts.apiPrefix = spec.App.APIPrefix
	return nil
}

func applySDKConfigDefaults(opts *SdkOptions) error {
	discovery, err := codegen.DiscoverConfig(".")
	if err != nil {
		return err
	}
	if !discovery.Found || !sameDir(discovery.ProjectDir, ".") {
		return nil
	}
	type sdkEntry struct {
		opts   SdkOptions
		outDir string
	}
	var entries []sdkEntry
	for i, gen := range discovery.Config.Codegen.Generators {
		if gen.Name != "sdk" || gen.Extension != "" {
			continue
		}
		decoded, err := decodeSDKEntry(i, gen)
		if err != nil {
			return err
		}
		out := gen.Output
		if out == "" {
			out = "sdk"
		}
		entries = append(entries, sdkEntry{decoded, filepath.ToSlash(filepath.Join(discovery.Config.Codegen.Output, out))})
	}
	picked := entries
	if opts.fromOpenAPI != "" {
		picked = slices.DeleteFunc(slices.Clone(picked), func(e sdkEntry) bool { return !sameOpenAPISource(e.opts.fromOpenAPI, opts.fromOpenAPI) })
	}
	if opts.OutDir != "" && (opts.fromOpenAPI == "" || len(picked) > 1) {
		picked = slices.DeleteFunc(slices.Clone(picked), func(e sdkEntry) bool { return !samePath(e.outDir, opts.OutDir) })
	}
	if len(picked) > 1 {
		var dirs []string
		for _, e := range picked {
			dirs = append(dirs, e.outDir)
		}
		return fmt.Errorf("gofastr.settings.yml lists %d sdk entries (%s); pass --out with one of those directories, or --from-openapi with an entry's document, to pick one", len(picked), strings.Join(dirs, ", "))
	}
	if len(picked) == 1 && opts.OutDir == "" {
		opts.OutDir = picked[0].outDir
	}
	out := cmp.Or(opts.OutDir, sdkDefaultOut)
	for _, e := range entries {
		if !pathsOverlap(e.outDir, out) || len(picked) == 1 && e.outDir == picked[0].outDir {
			continue
		}
		source := "the entity set"
		if e.opts.fromOpenAPI != "" {
			source = "the OpenAPI document " + e.opts.fromOpenAPI
		}
		return fmt.Errorf("%s is where the sdk entry for %s in gofastr.settings.yml writes, and this run is not that entry; pass --out to write somewhere else", out, source)
	}
	if len(picked) == 0 {
		return nil
	}
	entry := picked[0].opts
	for _, field := range []struct {
		flag       string
		dst, entry *string
	}{
		{"name", &opts.name, &entry.name},
		{"api-prefix", &opts.apiPrefix, &entry.apiPrefix},
		{"module", &opts.module, &entry.module},
		{"base-url", &opts.baseURL, &entry.baseURL},
		{"sdk-version", &opts.sdkVersion, &entry.sdkVersion},
		{"from-openapi", &opts.fromOpenAPI, &entry.fromOpenAPI},
	} {
		if *field.dst == "" && !opts.set[field.flag] {
			*field.dst = *field.entry
			if entry.set[field.flag] {
				if opts.set == nil {
					opts.set = map[string]bool{}
				}
				opts.set[field.flag] = true
			}
		}
	}
	for _, field := range []struct {
		flag       string
		dst, entry *[]string
	}{
		{"target", &opts.targets, &entry.targets},
		{"only", &opts.only, &entry.only},
		{"exclude", &opts.exclude, &entry.exclude},
	} {
		if len(*field.dst) == 0 && !opts.set[field.flag] {
			*field.dst = *field.entry
		}
	}
	return nil
}

func resolvedAbs(p string) (string, error) {
	abs, err := filepath.Abs(p)
	if err != nil {
		return "", err
	}
	rest := ""
	for dir := abs; ; dir = filepath.Dir(dir) {
		if real, err := filepath.EvalSymlinks(dir); err == nil {
			return filepath.Join(real, rest), nil
		}
		if filepath.Dir(dir) == dir {
			return abs, nil
		}
		rest = filepath.Join(filepath.Base(dir), rest)
	}
}

func samePath(a, b string) bool {
	absA, errA := resolvedAbs(a)
	absB, errB := resolvedAbs(b)
	return errA == nil && errB == nil && absA == absB
}

func pathsOverlap(a, b string) bool {
	absA, errA := resolvedAbs(a)
	absB, errB := resolvedAbs(b)
	if errA != nil || errB != nil {
		return true
	}
	inside := func(dir, p string) bool {
		rel, err := filepath.Rel(dir, p)
		return err == nil && filepath.IsLocal(rel)
	}
	return inside(absA, absB) || inside(absB, absA)
}

func buildSDKSpec(decls []framework.EntityDeclaration, opts *SdkOptions) (sdkSpec, error) {
	selected, err := selectDeclarations(decls, opts.only, opts.exclude, func(string) string { return "--only/--exclude" })
	if err != nil {
		return sdkSpec{}, err
	}
	spec, err := settleSDKSpec(opts)
	if err != nil {
		return sdkSpec{}, err
	}
	return addSDKEntities(spec, selected)
}

func settleSDKSpec(opts *SdkOptions) (sdkSpec, error) {
	for _, t := range opts.targets {
		if !sdkValidTargets[t] {
			return sdkSpec{}, fmt.Errorf("--target: unknown target %q (valid: go, js)", t)
		}
	}
	if len(opts.targets) == 0 {
		opts.targets = []string{"go", "js"}
	}
	sort.Strings(opts.targets)
	if opts.OutDir == "" {
		opts.OutDir = sdkDefaultOut
	}

	abs, err := filepath.Abs(".")
	if err != nil {
		return sdkSpec{}, err
	}
	modulePath, moduleRoot := project.FindEnclosingGoMod(abs)
	if opts.name == "" {
		if modulePath != "" {
			opts.name = strings.ToLower(filepath.Base(filepath.FromSlash(modulePath)))
		} else {
			opts.name = strings.ToLower(filepath.Base(abs))
		}
	}
	if opts.module == "" {
		opts.module = "local/" + strings.ReplaceAll(strings.ToLower(opts.name), "_", "-") + "-sdk"
	}
	if opts.sdkVersion == "" {
		opts.sdkVersion = "0.0.0-dev"
	}
	if err := validateSDKModulePath(opts.module); err != nil {
		return sdkSpec{}, err
	}

	gofastrVersion := "dev"
	if moduleRoot != "" {
		if v, _, err := project.GoModGofastrVersion(moduleRoot); err == nil && v != "" {
			gofastrVersion = v
		}
	}

	apiPrefix := strings.Trim(strings.TrimSpace(opts.apiPrefix), "/")
	if apiPrefix != "" {
		apiPrefix = "/" + apiPrefix
	}

	appName := sdkMarkdownSafe(opts.name)
	spec := sdkSpec{
		App:            appName,
		SDKVersion:     opts.sdkVersion,
		GofastrVersion: gofastrVersion,
		Module:         opts.module,
		GoDirectory:    sdkFenceWord(appName) + "-sdk",
		BaseURL:        opts.baseURL,
		APIPrefix:      apiPrefix,
	}
	if opts.stampTime {
		spec.GeneratedAt = time.Now().UTC()
	}
	return spec, nil
}

func addSDKEntities(spec sdkSpec, selected []framework.EntityDeclaration) (sdkSpec, error) {
	structOwners := map[string]string{}
	propOwners := map[string]string{}
	for _, decl := range selected {
		ent := buildEntityModel(decl, cliVerbs)
		if !project.IsGoIdentifier(ent.Struct) {
			return sdkSpec{}, fmt.Errorf("entity %q does not produce a valid Go identifier (%q); it is emitted as the SDK's generated type names. Rename it to letters, digits and underscores starting with a letter", decl.Name, ent.Struct)
		}
		if strings.ContainsFunc(ent.Table, func(r rune) bool { return r == '"' || r == '\\' || r < 0x20 || r == 0x7f }) {
			return sdkSpec{}, fmt.Errorf("entity %q table %q contains a character that cannot survive the Go string literals the SDK emits it into. Rename the table", decl.Name, ent.Table)
		}
		if !isJSIdentifier(jsResourceProp(ent)) {
			return sdkSpec{}, fmt.Errorf("entity %q table %q does not produce a valid JavaScript identifier (%q); the SDK emits it as the unquoted `export const %sFields` declaration in client.js, which the docs site serves to browsers. Rename the table to letters, digits, dashes and underscores", decl.Name, ent.Table, jsResourceProp(ent), jsResourceProp(ent))
		}
		if prop := jsResourceProp(ent); slices.Contains(jsClientMembers, prop) || slices.Contains(jsObjectMembers, prop) {
			return sdkSpec{}, fmt.Errorf("entity %q table %q derives the client property %s, which is reserved: the JS Client already defines it. Rename the table", decl.Name, ent.Table, prop)
		}
		if prev, dup := propOwners[jsResourceProp(ent)]; dup {
			return sdkSpec{}, fmt.Errorf("entities %q and %q both derive the client property %s (their tables collapse under camelCase): client.js would declare it twice and the second binding would win. Rename one table", prev, decl.Name, jsResourceProp(ent))
		}
		if prev, dup := structOwners[ent.Struct]; dup {
			return sdkSpec{}, fmt.Errorf("entities %q and %q both derive the Go type %s: client.go would declare it twice and only fail when the consumer builds the SDK. Rename one entity", prev, decl.Name, ent.Struct)
		}
		propOwners[jsResourceProp(ent)] = decl.Name
		structOwners[ent.Struct] = decl.Name
		if err := validateDeclarationStates(decl); err != nil {
			return sdkSpec{}, fmt.Errorf("entity %q: %w", decl.Name, err)
		}
		spec.Decls = append(spec.Decls, decl)
		spec.Entities = append(spec.Entities, ent)
	}
	if len(spec.Decls) == 0 {
		return sdkSpec{}, fmt.Errorf("selection matches no entities: nothing to generate")
	}
	if err := checkEndpointReturns(spec.Decls); err != nil {
		return sdkSpec{}, err
	}
	if err := checkDTSTypeNames(spec); err != nil {
		return sdkSpec{}, err
	}
	return spec, nil
}

func renderSDKFiles(spec sdkSpec, targets []string, dist bool) ([]GeneratedFile, error) {
	return renderSDKSource(spec, sdkSource{
		goFiles: func() ([]GeneratedFile, error) { return renderSDKGoFiles(spec) },
		jsFiles: func() []GeneratedFile { return renderSDKJSFiles(spec) },
		scope: func(m *sdk.Manifest) error {
			for _, decl := range spec.Decls {
				m.Entities = append(m.Entities, decl.Name)
			}
			sort.Strings(m.Entities)
			hash, err := SdkSchemaHash(spec.Decls)
			m.SchemaHash = hash
			return err
		},
	}, targets, dist)
}

type sdkSource struct {
	goFiles func() ([]GeneratedFile, error)
	jsFiles func() []GeneratedFile
	scope   func(*sdk.Manifest) error
}

func renderSDKSource(spec sdkSpec, src sdkSource, targets []string, dist bool) ([]GeneratedFile, error) {
	want := map[string]bool{}
	for _, t := range targets {
		want[t] = true
	}

	var files []GeneratedFile
	artifacts := map[string]sdk.Artifact{}
	var distFiles []GeneratedFile

	record := func(key string, artifact sdk.Artifact, data []byte) {
		sum := sha256.Sum256(data)
		artifact.SHA256 = fmt.Sprintf("%x", sum)
		artifact.Bytes = int64(len(data))
		artifacts[key] = artifact
		distFiles = append(distFiles, GeneratedFile{Name: "dist/" + artifact.File, Content: string(data)})
	}

	if want["go"] {
		goFiles, err := src.goFiles()
		if err == nil {
			goFiles, err = StampGeneratedFiles("sdk", goFiles)
		}
		if err != nil {
			return nil, err
		}
		for _, f := range goFiles {
			files = append(files, GeneratedFile{Name: "go/" + f.Name, Content: f.Content})
		}
		if dist {
			var zipFiles []sdk.File
			for _, f := range goFiles {
				zipFiles = append(zipFiles, sdk.File{Path: f.Name, Data: []byte(f.Content)})
			}
			raw, err := sdk.PackZip(spec.GoDirectory, zipFiles)
			if err != nil {
				return nil, err
			}
			record("go", sdk.Artifact{File: sdk.GoArtifact, Module: spec.Module, Directory: spec.GoDirectory}, raw)
		}
	}

	if want["js"] {
		jsFiles, err := StampGeneratedFiles("sdk", src.jsFiles())
		if err != nil {
			return nil, err
		}
		for _, f := range jsFiles {
			files = append(files, GeneratedFile{Name: "js/" + f.Name, Content: f.Content})
			if !dist {
				continue
			}
			switch f.Name {
			case sdk.JSArtifact:
				record("js", sdk.Artifact{File: f.Name}, []byte(f.Content))
			case sdk.JSTypesArtifact:
				record("js-types", sdk.Artifact{File: f.Name}, []byte(f.Content))
			}
		}
	}

	if dist {
		manifest := sdk.Manifest{
			SchemaVersion:  sdk.SchemaVersion,
			App:            spec.App,
			SDKVersion:     spec.SDKVersion,
			GofastrVersion: spec.GofastrVersion,
			GeneratedAt:    spec.GeneratedAt,
			Artifacts:      artifacts,
		}
		if err := src.scope(&manifest); err != nil {
			return nil, err
		}
		raw, err := json.MarshalIndent(manifest, "", "  ")
		if err != nil {
			return nil, err
		}
		distFiles = append(distFiles, GeneratedFile{Name: "dist/" + sdk.ManifestFile, Content: string(raw) + "\n"})
		files = append(files, distFiles...)
	}
	return files, nil
}

// SdkSchemaHash is the drift hash over the selected declarations under camel JSON case, the case the artifacts speak.
func SdkSchemaHash(decls []framework.EntityDeclaration) (string, error) {
	var named []sdk.NamedConfig
	for _, decl := range decls {
		cfg, err := decl.Config()
		if err != nil {
			return "", fmt.Errorf("entity %q: %w", decl.Name, err)
		}
		named = append(named, sdk.NamedConfig{Name: decl.Name, Config: cfg})
	}
	return sdk.SchemaHash(named, string(framework.CaseCamel)), nil
}

