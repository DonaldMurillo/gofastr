func sdkBracketKeysNote(spec sdkSpec) string {
	var lines []string
	for _, e := range spec.Entities {
		for _, key := range e.filterKeys.AmbiguousKeys() {
			safe := sdkFenceWord(key)
			lines = append(lines, fmt.Sprintf("- `%s` on `%s`: send `%s` (equality on `%s`) or `%s`",
				safe, sdkFenceWord(e.Table), filter.BracketKey(safe, filter.OpEq), safe, bracketSplit(safe)))
		}
	}
	var note string
	if len(lines) > 0 {
		note = "These filter keys name a field and also another field plus an operator\nsuffix, so the server answers the bare key 400. Send the operator word in\nbrackets after the whole field name (eq, ne, gt, gte, lt, lte, like, in):\n\n" + strings.Join(lines, "\n") + "\n\n"
	}
	var controls []string
	for _, e := range spec.Entities {
		noQuery := map[string]bool{}
		for _, f := range e.Fields {
			noQuery[f.Snake] = f.NoQuery
		}
		for _, key := range e.filterKeys.ControlNamedKeys() {
			if key == "q" || noQuery[key] {
				continue
			}
			safe := sdkFenceWord(key)
			controls = append(controls, fmt.Sprintf("- `%s` on `%s`: send `%s`", safe, sdkFenceWord(e.Table), filter.BracketKey(safe, filter.OpEq)))
		}
	}
	if len(controls) > 0 {
		note += "These fields share their name with a list control, so the bare key sets\nthe control (`?page=2` is the second page). Filter the field by its bracket\nkey:\n\n" + strings.Join(controls, "\n") + "\n\n"
	}
	return note
}

func bracketSplit(key string) string {
	for _, s := range filter.FilterSuffixes {
		if base, ok := strings.CutSuffix(key, s.Suffix); ok {
			return filter.BracketKey(base, s.Op)
		}
	}
	return key
}

func sdkExampleFilter(fields []cliField) (field *cliField, op string) {
	for i := range fields {
		if !fields[i].NoQuery && cliFieldAcceptsGte(fields[i]) {
			f := fields[i]
			return &f, "_gte"
		}
	}
	for i := range fields {
		if !fields[i].NoQuery && !fields[i].NoEq {
			f := fields[i]
			return &f, ""
		}
	}
	return nil, ""
}

func cliFieldAcceptsGte(f cliField) bool {
	for _, op := range f.FilterOps {
		if op.Param == "_gte" {
			return true
		}
	}
	return false
}

type sdkGenerator struct{}

func (sdkGenerator) Name() string { return "sdk" }

func (sdkGenerator) Generate(_ context.Context, genCtx *codegen.Context, cfg codegen.GeneratorConfig) ([]codegen.GeneratedFile, error) {
	dir := genCtx.ProjectDir
	if dir == "" {
		dir = "."
	}
	opts, err := decodeSDKEntry(-1, cfg)
	if err != nil {
		return nil, err
	}
	opts.OutDir = "gen/sdk"
	var files []GeneratedFile
	if opts.fromOpenAPI != "" {
		files, err = renderOpenAPISDK(&opts, dir)
	} else {
		files, err = renderEntitySDK(dir, &opts)
	}
	if err != nil {
		return nil, err
	}
	out := make([]codegen.GeneratedFile, 0, len(files))
	for _, f := range files {
		out = append(out, codegen.GeneratedFile{Path: f.Name, Content: f.Content})
	}
	return out, nil
}

func renderEntitySDK(dir string, opts *SdkOptions) ([]GeneratedFile, error) {
	decls, err := ReadAppDecls(dir)
	if err != nil {
		return nil, err
	}
	if len(decls) == 0 {
		return nil, fmt.Errorf("no entities package found in %s", dir)
	}
	if err := applySDKAppDefaults(dir, opts); err != nil {
		return nil, err
	}
	spec, err := buildSDKSpec(decls, opts)
	if err != nil {
		return nil, err
	}
	return renderSDKFiles(spec, opts.targets, true)
}
