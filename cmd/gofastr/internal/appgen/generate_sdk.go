// `gofastr generate sdk` emits downloadable client SDKs for the app's HTTP
// API: a standalone stdlib-only Go module (the same typed client the app
// embeds, packaged with its own go.mod) and a handrolled ESM client.js +
// client.d.ts pair, deliberately no npm packaging; publishing is the app
// owner's call. A dist/ directory holds the servable artifacts (sdk-go.zip,
// client.js, client.d.ts, manifest.json) that framework/sdkdocs hosts.
//
// SDK output is generator-owned and regenerates IN PLACE: when the docs
// site warns that the artifacts drifted from the live schema, the fix is
// re-running this command, so a conflict prompt would only add friction. Point --out somewhere private if
// you need to keep an old build.

type SdkOptions struct {
	OutDir     string
	name       string
	apiPrefix  string
	module     string
	baseURL    string
	sdkVersion string
	targets    []string
	only       []string
	exclude    []string
	noArchive  bool
	dryRun     bool
	json       bool
	// set names the value flags given on the command line, empty ones
	// included: an explicit --only= clears the settings entry's list
	// rather than leaving it to fill in.
	set map[string]bool
}

// sdkSpec is the derived input the SDK renderers consume: the shared
// per-entity model (buildEntityModel) plus the raw declarations for the
// emitters that mirror renderClient's exact field walk.
type sdkSpec struct {
	App            string
	SDKVersion     string
	GofastrVersion string
	Module         string
	BaseURL        string
	APIPrefix      string // "" or "/api": baked into docs/examples, not client paths
	Decls          []framework.EntityDeclaration
	Entities       []cliEntity
}

// Header returns the DO-NOT-EDIT stamp shared by every generated SDK file.
//
// Every interpolated value is scrubbed here rather than at each use site,
// because the stamp lands in four different comment syntaxes: a Go `//` line
// comment (client.go), a JavaScript `//` line comment (client.js), a
// TypeScript `//` line comment (client.d.ts) and an HTML comment inside
// markdown (both READMEs). Only client.go had a parse gate behind it
// (format.Source in renderSDKGoFiles); the other three had nothing, and
// client.js is the artifact framework/sdkdocs serves to browsers.
func (s sdkSpec) Header() string {
	return fmt.Sprintf("Code generated by gofastr %s (sdk %s) for %s. DO NOT EDIT.",
		sdkCommentSafe(s.GofastrVersion), sdkCommentSafe(s.SDKVersion), sdkCommentSafe(s.App))
}

// sdkCommentSafe makes a value inert inside every comment syntax the SDK
// emitters use. `name` and `sdk_version` come from --name/--sdk-version or from
// the project's own gofastr.settings.yml (applySDKConfigDefaults), the same
// provenance the codegen exec gate already treats as potentially hostile,
// because a config committed to a repo you cloned is not a config you wrote.
//
// Two escapes matter. Any C0 byte ends a `//` comment: a newline in `name`
// puts the rest of the value at statement position in client.js, which
// sdkdocs serves to browsers. And `-->` ends the HTML comment the READMEs wrap
// the stamp in. Strip the first, defuse the second (plus `*/` for block
// comments, so a future emitter that uses one inherits the guard).
func sdkCommentSafe(value string) string {
	var b strings.Builder
	b.Grow(len(value))
	for _, r := range value {
		if r < 0x20 || r == 0x7f {
			continue
		}
		b.WriteRune(r)
	}
	out := b.String()
	out = strings.ReplaceAll(out, "-->", "- ->")
	return strings.ReplaceAll(out, "*/", "* /")
}

// sdkMarkdownSafe makes a config-provenance value inert in the MARKDOWN
// contexts the READMEs interpolate it into (H1 heading, prose line): the
// sdkCommentSafe strip of C0/DEL (a newline moves the rest of the value
// to body/fence-line position) plus the fence openers ``` and ~~~, so the
// value can neither start its own line nor open its own code block. The
// install FENCE slot is stricter still: see sdkFenceWord.
func sdkMarkdownSafe(value string) string {
	var b strings.Builder
	b.Grow(len(value))
	for _, r := range value {
		if r < 0x20 || r == 0x7f || r == '`' || r == '~' {
			continue
		}
		b.WriteRune(r)
	}
	out := b.String()
	out = strings.ReplaceAll(out, "-->", "- ->")
	return strings.ReplaceAll(out, "*/", "* /")
}

// sdkFenceWord reduces the app name to the bytes that are inert inside
// the README's ```sh install fence (`go mod edit -replace <module>=./<dir>`),
// which an operator copies and pastes into a shell: the module-path
// alphabet only. A newline would become its own shell line, and spaces,
// pipes, backticks and quotes all change how the pasted line parses, so
// they are dropped rather than escaped — hostile junk can only mangle the
// directory hint, never restructure the command.
func sdkFenceWord(value string) string {
	var b strings.Builder
	b.Grow(len(value))
	for _, r := range value {
		switch {
		case r >= 'a' && r <= 'z', r >= 'A' && r <= 'Z', r >= '0' && r <= '9',
			r == '-', r == '_', r == '.', r == '~':
			b.WriteRune(r)
		}
	}
	return b.String()
}

// sdkModulePathRe is the subset of Go module paths this generator will emit
// into the SDK's go.mod. Deliberately narrower than the spec allows: the value
// is interpolated into `module %s` with nothing between it and the next
// directive, so a single newline turns it into `require`/`replace` lines that
// the SDK's consumers build. A `replace` naming an attacker-controlled
// directory is arbitrary code execution on `go build` in a downstream repo.
var sdkModulePathRe = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9._~/-]*$`)

func validateSDKModulePath(module string) error {
	if !sdkModulePathRe.MatchString(module) {
		return fmt.Errorf("--module %q is not a usable Go module path. Use letters, digits, dot, dash, underscore, tilde and slash (e.g. example.com/app-sdk)", module)
	}
	if strings.Contains(module, "//") || strings.HasSuffix(module, "/") {
		return fmt.Errorf("--module %q is not a usable Go module path: empty path element", module)
	}
	return nil
}

var sdkValidTargets = map[string]bool{"go": true, "js": true}

// RunGenerateSDK implements `gofastr generate sdk`.
func RunGenerateSDK(args []string) {
	opts, err := parseSDKOptions(args)
	if err != nil {
		cli.Fail("%v", err)
		cli.Info("Usage: gofastr generate sdk [--target=go,js] [--out=gen/sdk] [--name=<app>] [--api-prefix=api] [--only=a,b] [--exclude=c] [--module=<path>] [--base-url=<url>] [--sdk-version=<semver>] [--no-archive] [--dry-run] [--json]")
		cli.OsExit(1)
		return
	}
	if err := ApplySDKConfigDefaults(&opts); err != nil {
		cli.Fail("%v", err)
		cli.OsExit(1)
		return
	}

	decls, err := ReadAppDecls(".")
	if err != nil {
		cli.Fail("read entities: %v", err)
		cli.OsExit(1)
		return
	}
	if len(decls) == 0 {
		cli.Fail("no entities package found in the current directory")
		cli.Info("Run from your app root (the directory holding entities/), or generate the app first: gofastr generate app <spec.yml>.")
		cli.OsExit(1)
		return
	}

	spec, err := buildSDKSpec(decls, &opts)
	if err != nil {
		if opts.dryRun && opts.json {
			printGeneratedErrorsJSON(err)
			cli.OsExit(1)
			return
		}
		cli.Fail("%v", err)
		cli.OsExit(1)
		return
	}
	if err := validateOutputDir(opts.OutDir); err != nil {
		cli.Fail("%v", err)
		cli.OsExit(1)
		return
	}

	files, err := renderSDKFiles(spec, opts.targets, !opts.noArchive)
	if err != nil {
		cli.Fail("SDK generation failed: %v", err)
		cli.OsExit(1)
		return
	}

	if opts.dryRun {
		if opts.json {
			printGeneratedFilesJSON(files)
			return
		}
		cli.Info("Would generate %d file(s) in %s:", len(files), opts.OutDir)
		for _, f := range files {
			fmt.Printf("    %s\n", filepath.Join(opts.OutDir, f.Name))
		}
		return
	}

	for _, f := range files {
		if existing, rerr := readFileUnder(opts.OutDir, f.Name); rerr == nil {
			warnDerivedEdit("sdk", filepath.Join(opts.OutDir, f.Name), string(existing), "the entity declarations")
		}
	}
	fileSet, err := FileSetFromGeneratedFiles(files, "sdk")
	if err != nil {
		cli.Fail("SDK generation failed: %v", err)
		cli.OsExit(1)
		return
	}
	writeOpts := codegen.WriteOptions{
		OutputRoot:   opts.OutDir,
		SkipManifest: true,
		Conflict:     codegen.ConflictOverwrite,
	}
	if err := codegen.WriteFiles(fileSet, writeOpts); err != nil {
		cli.Fail("Failed to write generated files: %v", err)
		cli.OsExit(1)
		return
	}
	if opts.json {
		printGeneratedFilesJSON(files)
		return
	}
	cli.Success("Generated %d file(s) in %s", len(files), opts.OutDir)
	fmt.Println()
	fmt.Println("  Next steps:")
	fmt.Printf("    serve the downloads: sdkdocs.Mount(site, app.Router(), sdkdocs.Config{Registry: app.Registry, Artifacts: os.DirFS(%q)})\n", filepath.ToSlash(filepath.Join(opts.OutDir, "dist")))
	fmt.Println("    re-run this command whenever entities change: output regenerates in place")
}

func parseSDKOptions(args []string) (SdkOptions, error) {
	opts := SdkOptions{set: map[string]bool{}}
	for i := 0; i < len(args); i++ {
		arg := args[i]
		nextValue := func() (string, bool) {
			if i+1 < len(args) && !strings.HasPrefix(args[i+1], "--") {
				i++
				return args[i], true
			}
			return "", false
		}
		value := func(prefix string) (string, bool) {
			if strings.HasPrefix(arg, prefix+"=") {
				return strings.TrimPrefix(arg, prefix+"="), true
			}
			if arg == prefix {
				return nextValue()
			}
			return "", false
		}
		switch {
		case arg == "--no-archive":
			opts.noArchive = true
		case arg == "--dry-run":
			opts.dryRun = true
		case arg == "--json":
			opts.json = true
		default:
			if v, ok := value("--out"); ok {
				opts.OutDir = v
			} else if v, ok := value("--name"); ok {
				opts.name = v
			} else if v, ok := value("--api-prefix"); ok {
				opts.apiPrefix = v
			} else if v, ok := value("--module"); ok {
				opts.module = v
			} else if v, ok := value("--base-url"); ok {
				opts.baseURL = v
			} else if v, ok := value("--sdk-version"); ok {
				opts.sdkVersion = v
			} else if v, ok := value("--target"); ok {
				opts.targets = splitCommaList(v)
			} else if v, ok := value("--only"); ok {
				opts.only = splitCommaList(v)
			} else if v, ok := value("--exclude"); ok {
				opts.exclude = splitCommaList(v)
			} else {
				return opts, fmt.Errorf("unknown flag: %s", arg)
			}
			flag, _, _ := strings.Cut(strings.TrimPrefix(arg, "--"), "=")
			opts.set[flag] = true
		}
	}
	for _, t := range opts.targets {
		if !sdkValidTargets[t] {
			return opts, fmt.Errorf("--target: unknown target %q (valid: go, js)", t)
		}
	}
	return opts, nil
}

// ApplySDKConfigDefaults fills unset options from a discovered codegen
// config's generator entry named "sdk" (flags always win), so projects can
// pin their SDK settings in gofastr.settings.yml:
//
//	codegen:
//	  generators:
//	    - name: sdk
//	      output: sdk
//	      config: {targets: [go, js], name: myapp, base_url: "https://api.example.com"}
//
// The same entry drives `gofastr generate --config` through the registered
// in-process generator (sdkGenerator), so both invocation paths agree.
func ApplySDKConfigDefaults(opts *SdkOptions) error {
	discovery, err := codegen.DiscoverConfig(".")
	if err != nil {
		return err
	}
	// A settings file in a parent directory names paths from its own
	// directory, while this run writes from the current one.
	if !discovery.Found || !sameDir(discovery.ProjectDir, ".") {
		return nil
	}
	for i, gen := range discovery.Config.Codegen.Generators {
		if gen.Name != "sdk" || gen.Extension != "" {
			continue
		}
		entry, err := decodeSDKEntry(i, gen)
		if err != nil {
			return err
		}
		if opts.OutDir == "" {
			out := gen.Output
			if out == "" {
				out = "sdk"
			}
			opts.OutDir = filepath.ToSlash(filepath.Join(discovery.Config.Codegen.Output, out))
		}
		for _, field := range []struct {
			flag       string
			dst, entry *string
		}{
			{"name", &opts.name, &entry.name},
			{"api-prefix", &opts.apiPrefix, &entry.apiPrefix},
			{"module", &opts.module, &entry.module},
			{"base-url", &opts.baseURL, &entry.baseURL},
			{"sdk-version", &opts.sdkVersion, &entry.sdkVersion},
		} {
			if *field.dst == "" && !opts.set[field.flag] {
				*field.dst = *field.entry
			}
		}
		for _, field := range []struct {
			flag       string
			dst, entry *[]string
		}{
			{"target", &opts.targets, &entry.targets},
			{"only", &opts.only, &entry.only},
			{"exclude", &opts.exclude, &entry.exclude},
		} {
			if len(*field.dst) == 0 && !opts.set[field.flag] {
				*field.dst = *field.entry
			}
		}
		return nil
	}
	return nil
}

// buildSDKSpec validates selection and derives the renderer input. It
// mutates opts only to settle defaults (name, out dir, targets).
func buildSDKSpec(decls []framework.EntityDeclaration, opts *SdkOptions) (sdkSpec, error) {
	for _, sel := range [][]string{opts.only, opts.exclude} {
		for _, name := range sel {
			if !cliAnyEntityMatches(decls, name) {
				return sdkSpec{}, fmt.Errorf("--only/--exclude: no entity named %q", name)
			}
		}
	}
	for _, t := range opts.targets {
		if !sdkValidTargets[t] {
			return sdkSpec{}, fmt.Errorf("--target: unknown target %q (valid: go, js)", t)
		}
	}
	if len(opts.targets) == 0 {
		opts.targets = []string{"go", "js"}
	}
	sort.Strings(opts.targets)
	if opts.OutDir == "" {
		opts.OutDir = "gen/sdk"
	}

	abs, err := filepath.Abs(".")
	if err != nil {
		return sdkSpec{}, err
	}
	modulePath, moduleRoot := project.FindEnclosingGoMod(abs)
	if opts.name == "" {
		// The module path base names the app better than the directory
		// (temp dirs, checkouts named "src", …).
		if modulePath != "" {
			opts.name = strings.ToLower(filepath.Base(filepath.FromSlash(modulePath)))
		} else {
			opts.name = strings.ToLower(filepath.Base(abs))
		}
	}
	if opts.module == "" {
		opts.module = "local/" + strings.ReplaceAll(strings.ToLower(opts.name), "_", "-") + "-sdk"
	}
	if opts.sdkVersion == "" {
		opts.sdkVersion = "0.0.0-dev"
	}
	if err := validateSDKModulePath(opts.module); err != nil {
		return sdkSpec{}, err
	}

	gofastrVersion := "dev"
	if moduleRoot != "" {
		if v, _, err := project.GoModGofastrVersion(moduleRoot); err == nil && v != "" {
			gofastrVersion = v
		}
	}

	apiPrefix := strings.Trim(strings.TrimSpace(opts.apiPrefix), "/")
	if apiPrefix != "" {
		apiPrefix = "/" + apiPrefix
	}

	// App is config-provenance (--name / gofastr.settings.yml, the same
	// provenance the exec gate and sdkCommentSafe treat as hostile) and
	// lands raw in both READMEs' H1/prose and (as the -sdk directory) in
	// the install fence. Scrub it once here; renderSDKGoReadme applies
	// the stricter fence reduction at the fence slot itself.
	spec := sdkSpec{
		App:            sdkMarkdownSafe(opts.name),
		SDKVersion:     opts.sdkVersion,
		GofastrVersion: gofastrVersion,
		Module:         opts.module,
		BaseURL:        opts.baseURL,
		APIPrefix:      apiPrefix,
	}

	matchesAny := func(decl framework.EntityDeclaration, names []string) bool {
		for _, name := range names {
			if cliEntityMatches(decl, name) {
				return true
			}
		}
		return false
	}
	structOwners := map[string]string{} // derived Go type name → declaring entity
	propOwners := map[string]string{}   // derived client.js property → declaring entity
	for _, decl := range decls {
		if len(opts.only) > 0 && !matchesAny(decl, opts.only) {
			continue
		}
		if matchesAny(decl, opts.exclude) {
			continue
		}
		ent := buildEntityModel(decl, cliVerbs)
		// `generate sdk` reads the same hand-written entities/*.go the CLI
		// generator reads (packReadEntities), so it inherits the same trust
		// boundary buildCLIEntity defends: the derived struct name lands in
		// identifier position (`type %s struct`, `func (c *Client)
		// List%s`), and the table lands raw inside "/%s" path literals in
		// renderClientEntity. A table like x"+PWN()+"y parses as Go, so the
		// format.Source gate renderSDKGoFiles leans on waves it through —
		// the refusal belongs here, before any target renders.
		if !project.IsGoIdentifier(ent.Struct) {
			return sdkSpec{}, fmt.Errorf("entity %q does not produce a valid Go identifier (%q); it is emitted as the SDK's generated type names. Rename it to letters, digits and underscores starting with a letter", decl.Name, ent.Struct)
		}
		if strings.ContainsFunc(ent.Table, func(r rune) bool { return r == '"' || r == '\\' || r < 0x20 || r == 0x7f }) {
			return sdkSpec{}, fmt.Errorf("entity %q table %q contains a character that cannot survive the Go string literals the SDK emits it into. Rename the table", decl.Name, ent.Table)
		}
		// jsResourceProp(ent) is toCamelJSON(ent.Table), and toCamelCase
		// only splits on "_", "-" and space: every other byte survives
		// into the UNQUOTED `export const %sFields` declaration in the
		// executable client.js that sdkdocs serves to browsers. A table
		// like "x =(console.log)(49414), y" passes the literal gate above
		// (no quote, backslash or control byte) and its derived property
		// lands at statement position the moment the artifact is
		// imported. A declaration name cannot be quoted the way the
		// object-literal keys are, so the property must BE an identifier.
		// The d.ts twin (`export declare const %sFields`, `readonly %s:`)
		// shares the gate; ent.Struct slots are covered by isGoIdentifier
		// (an ASCII subset of this grammar).
		if !isJSIdentifier(jsResourceProp(ent)) {
			return sdkSpec{}, fmt.Errorf("entity %q table %q does not produce a valid JavaScript identifier (%q); the SDK emits it as the unquoted `export const %sFields` declaration in client.js, which the docs site serves to browsers. Rename the table to letters, digits, dashes and underscores", decl.Name, ent.Table, jsResourceProp(ent), jsResourceProp(ent))
		}
		// The property binds on the Client (this["posts"] = new Resource),
		// so a table named after a Client member overwrites it: "token"
		// replaced the credential and every request sent "Bearer [object
		// Object]".
		if prop := jsResourceProp(ent); slices.Contains(jsClientMembers, prop) || slices.Contains(jsObjectMembers, prop) {
			return sdkSpec{}, fmt.Errorf("entity %q table %q derives the client property %s, which is reserved: the JS Client already defines it. Rename the table", decl.Name, ent.Table, prop)
		}
		// Derived names must be unique per target. jsResourceProp is
		// toCamelJSON(table), which collapses blog_posts / blog-posts /
		// "blog posts" onto blogPosts: two such entities emit `export const
		// blogPostsFields` twice (a SyntaxError in the client.js sdkdocs
		// serves to browsers) and a second `this["blogPosts"]` binding that
		// silently re-points the property at the other table. The Go side
		// has the same disease past its own gate: duplicate `type BlogPosts
		// struct` parses and only fails in the consumer's build. The
		// file-set collision guard cannot see inside one file.
		if prev, dup := propOwners[jsResourceProp(ent)]; dup {
			return sdkSpec{}, fmt.Errorf("entities %q and %q both derive the client property %s (their tables collapse under camelCase): client.js would declare it twice and the second binding would win. Rename one table", prev, decl.Name, jsResourceProp(ent))
		}
		if prev, dup := structOwners[ent.Struct]; dup {
			return sdkSpec{}, fmt.Errorf("entities %q and %q both derive the Go type %s: client.go would declare it twice and only fail when the consumer builds the SDK. Rename one entity", prev, decl.Name, ent.Struct)
		}
		propOwners[jsResourceProp(ent)] = decl.Name
		structOwners[ent.Struct] = decl.Name
		// Transition keys land in identifier slots in both targets (Go method
		// names, d.ts members) and in route literals; the entity boot check
		// never ran over a hand-written declaration, so the generators re-run
		// it here (one implementation, framework/entity's own).
		if err := validateDeclarationStates(decl); err != nil {
			return sdkSpec{}, fmt.Errorf("entity %q: %w", decl.Name, err)
		}
		spec.Decls = append(spec.Decls, decl)
		spec.Entities = append(spec.Entities, ent)
	}
	if len(spec.Decls) == 0 {
		return sdkSpec{}, fmt.Errorf("selection matches no entities: nothing to generate")
	}
	if err := checkEndpointReturns(spec.Decls); err != nil {
		return sdkSpec{}, err
	}
	if err := checkDTSTypeNames(spec); err != nil {
		return sdkSpec{}, err
	}
	return spec, nil
}

// renderSDKFiles produces every generated file, out-dir-relative: the go/
// and js/ source trees for the requested targets, plus dist/ (archives +
// manifest) unless archives are disabled. It stamps the provenance marker
// on the sources before it zips or hashes them, so the manifest describes
// the bytes the app serves.
func renderSDKFiles(spec sdkSpec, targets []string, dist bool) ([]GeneratedFile, error) {
	want := map[string]bool{}
	for _, t := range targets {
		want[t] = true
	}

	var files []GeneratedFile
	artifacts := map[string]sdk.Artifact{}
	var distFiles []GeneratedFile

	record := func(key, file, module string, data []byte) {
		sum := sha256.Sum256(data)
		artifacts[key] = sdk.Artifact{File: file, SHA256: fmt.Sprintf("%x", sum), Bytes: int64(len(data)), Module: module}
		distFiles = append(distFiles, GeneratedFile{Name: "dist/" + file, Content: string(data)})
	}

	if want["go"] {
		goFiles, err := renderSDKGoFiles(spec)
		if err == nil {
			goFiles, err = StampGeneratedFiles("sdk", goFiles)
		}
		if err != nil {
			return nil, err
		}
		for _, f := range goFiles {
			files = append(files, GeneratedFile{Name: "go/" + f.Name, Content: f.Content})
		}
		if dist {
			var zipFiles []sdk.File
			for _, f := range goFiles {
				zipFiles = append(zipFiles, sdk.File{Path: f.Name, Data: []byte(f.Content)})
			}
			raw, err := sdk.PackZip(spec.App+"-sdk", zipFiles)
			if err != nil {
				return nil, err
			}
			record("go", sdk.GoArtifact, spec.Module, raw)
		}
	}

	if want["js"] {
		jsFiles, err := StampGeneratedFiles("sdk", renderSDKJSFiles(spec))
		if err != nil {
			return nil, err
		}
		for _, f := range jsFiles {
			files = append(files, GeneratedFile{Name: "js/" + f.Name, Content: f.Content})
			if !dist {
				continue
			}
			switch f.Name {
			case sdk.JSArtifact:
				record("js", sdk.JSArtifact, "", []byte(f.Content))
			case sdk.JSTypesArtifact:
				record("js-types", sdk.JSTypesArtifact, "", []byte(f.Content))
			}
		}
	}

	if dist {
		var names []string
		for _, decl := range spec.Decls {
			names = append(names, decl.Name)
		}
		sort.Strings(names)
		hash, err := SdkSchemaHash(spec.Decls)
		if err != nil {
			return nil, err
		}
		manifest := sdk.Manifest{
			SchemaVersion:  sdk.SchemaVersion,
			App:            spec.App,
			SDKVersion:     spec.SDKVersion,
			GofastrVersion: spec.GofastrVersion,
			GeneratedAt:    time.Now().UTC(),
			Entities:       names,
			SchemaHash:     hash,
			Artifacts:      artifacts,
		}
		raw, err := json.MarshalIndent(manifest, "", "  ")
		if err != nil {
			return nil, err
		}
		distFiles = append(distFiles, GeneratedFile{Name: "dist/" + sdk.ManifestFile, Content: string(raw) + "\n"})
		files = append(files, distFiles...)
	}
	return files, nil
}

// SdkSchemaHash computes the drift-detection hash over the selected
// declarations, the generation-time half of the check sdkdocs.Mount
// recomputes against the live registry.
func SdkSchemaHash(decls []framework.EntityDeclaration) (string, error) {
	var named []sdk.NamedConfig
	for _, decl := range decls {
		cfg, err := decl.Config()
		if err != nil {
			return "", fmt.Errorf("entity %q: %w", decl.Name, err)
		}
		named = append(named, sdk.NamedConfig{Name: decl.Name, Config: cfg})
	}
	return sdk.SchemaHash(named), nil
}

// renderSDKGoFiles emits the standalone Go module: the renderClient output
// (identical to the in-app entities/client package) plus go.mod and README.
// client.go is gofmt'd here so the zipped bytes match the written tree.
func renderSDKGoFiles(spec sdkSpec) ([]GeneratedFile, error) {
	clientSrc := "// " + spec.Header() + "\n// Regenerate: gofastr generate sdk\n\n" + renderClient(spec.Decls)
	if err := refuseDuplicateDecls([]GeneratedFile{{Name: "client.go", Content: clientSrc}}); err != nil {
		return nil, err
	}
	formatted, err := format.Source([]byte(clientSrc))
	if err != nil {
		return nil, fmt.Errorf("generated client.go does not parse: %w", err)
	}
	goMod := fmt.Sprintf("module %s\n\ngo 1.21\n", spec.Module)
	return []GeneratedFile{
		{Name: "client.go", Content: string(formatted)},
		{Name: "go.mod", Content: goMod},
		{Name: "README.md", Content: renderSDKGoReadme(spec)},
	}, nil
}

func sdkExampleBaseURL(spec sdkSpec) string {
	return sdkExampleHost(spec) + spec.APIPrefix
}

// sdkExampleHost is the app origin WITHOUT the API prefix. Docs-site and
// download URLs mount on the host, only API calls live under the prefix.
func sdkExampleHost(spec sdkSpec) string {
	base := spec.BaseURL
	if base == "" {
		base = "https://your-app.example.com"
	}
	return strings.TrimRight(base, "/")
}

func renderSDKGoReadme(spec sdkSpec) string {
	first := spec.Entities[0]
	var sb strings.Builder
	fmt.Fprintf(&sb, "# %s Go SDK\n\n<!-- %s -->\n\n", spec.App, spec.Header())
	fmt.Fprintf(&sb, "A standalone, stdlib-only Go client for the %s HTTP API.\n\n", spec.App)
	sb.WriteString("## Install\n\nUnzip next to your project (or anywhere), then wire the module locally:\n\n")
	// sdkFenceWord, not the markdown scrub: this line is pasted into a
	// shell, so the directory hint is held to the module-path alphabet
	// (spec.Module itself is already regex-gated by validateSDKModulePath).
	fmt.Fprintf(&sb, "```sh\ngo mod edit -replace %s=./%s-sdk\ngo get %s\n```\n\n", spec.Module, sdkFenceWord(spec.App), spec.Module)
	sb.WriteString("## Use\n\n")
	fmt.Fprintf(&sb, "```go\nimport client %q\n\n", spec.Module)
	fmt.Fprintf(&sb, "c := client.NewClient(%q, nil)\nc.Token = os.Getenv(\"API_TOKEN\") // Bearer token minted via POST /auth/tokens\n\n", sdkExampleBaseURL(spec))
	fmt.Fprintf(&sb, "page, err := c.List%s(ctx, nil)\n```\n\n", first.Struct)
	sb.WriteString("The base URL must include the API prefix when the server mounts one (e.g. `/api`).\n\n")
	sb.WriteString("## Filtering, sorting, pagination\n\n")
	sb.WriteString("List methods take `url.Values`. Query parameter names are the **snake_case**\ncolumn names (responses are camelCase: that asymmetry is the server's contract):\n\n")
	// Pick the example column and operator the same way every surface
	// now does — from filter.OpSuitsType — so the snippet never shows a
	// `_gte` on a field whose type refuses it (a Bool or JSON column,
	// which answers 400 from the very snippet meant to demonstrate the
	// contract). NoQuery columns are skipped as before. A spec whose
	// every queryable column refuses the range operators gets the
	// plain-equality example.
	exampleField, filterOp := sdkExampleFilter(first.Fields)
	filterField := "id"
	if exampleField != nil {
		filterField = exampleField.Snake
	}
	// Spelled the way the server reads them: a bare key that reads two
	// ways (a field beside its name plus a suffix) takes the bracket form.
	eqKey := first.filterKeys.Key(filterField, filter.OpEq)
	if filterOp == "" {
		fmt.Fprintf(&sb, "```go\nparams := url.Values{}\nparams.Set(%q, \"x\")        // equality; _ne and _in suit every column\nparams.Set(\"sort\", \"-created_at\")\nparams.Set(\"limit\", \"50\")\nc.List%s(ctx, params)\n```\n\n", eqKey, first.Struct)
	} else {
		fmt.Fprintf(&sb, "```go\nparams := url.Values{}\nparams.Set(%q, \"x\")        // equality\nparams.Set(%q, \"x\")   // ne/gt/gte/lt/lte/like/in suffixes\nparams.Set(\"sort\", \"-created_at\")\nparams.Set(\"limit\", \"50\")\nc.List%s(ctx, params)\n```\n\n", eqKey, first.filterKeys.Key(filterField, filter.OpGte), first.Struct)
	}
	sb.WriteString(sdkBracketKeysNote(spec))
	sb.WriteString("Validation errors return `*APIError`; its `Body` holds the JSON envelope\n`{\"error\", \"success\", \"code\", \"reason\", \"fields\", \"field_reasons\"}`: `error` is the\nmessage in the request's locale and `reason` its stable code; `fields` keys are\nsnake_case column names and `field_reasons` holds each message's code.\n\n")
	sb.WriteString("`Do(ctx, method, path, body, out)` is the escape hatch for custom endpoints\nand presence-faithful `map[string]any` bodies. `Watch<Entity>` subscribes to\nthe live SSE feed. `Batch*` methods hit the atomic `_batch` routes.\n")
	return sb.String()
}

// sdkBracketKeysNote is the readme paragraph naming every filter key
// of the spec that reads two ways (a field beside its name plus a
// suffix), which the server answers 400, with the bracket spellings
// that pick one. A spec with no such key gets no paragraph, so its
// readme is unchanged.
func sdkBracketKeysNote(spec sdkSpec) string {
	var lines []string
	for _, e := range spec.Entities {
		for _, key := range e.filterKeys.AmbiguousKeys() {
			// sdkFenceWord holds the names to the code-span alphabet;
			// the brackets are added after, from the fixed op words.
			safe := sdkFenceWord(key)
			lines = append(lines, fmt.Sprintf("- `%s` on `%s`: send `%s` (equality on `%s`) or `%s`",
				safe, sdkFenceWord(e.Table), filter.BracketKey(safe, filter.OpEq), safe, bracketSplit(safe)))
		}
	}
	if len(lines) == 0 {
		return ""
	}
	return "These filter keys name a field and also another field plus an operator\nsuffix, so the server answers the bare key 400. Send the operator word in\nbrackets after the whole field name (eq, ne, gt, gte, lt, lte, like, in):\n\n" + strings.Join(lines, "\n") + "\n\n"
}

// bracketSplit spells the suffix reading of an ambiguous key in bracket
// form: stage_in is stage[in].
func bracketSplit(key string) string {
	for _, s := range filter.FilterSuffixes {
		if base, ok := strings.CutSuffix(key, s.Suffix); ok {
			return filter.BracketKey(base, s.Op)
		}
	}
	return key
}

// sdkExampleFilter picks the readme's example filter column and
// operator: the first queryable field whose type accepts a range
// comparison (filter.OpSuitsType, the one predicate every filter
// surface applies, via the CLI model's derived operator set) with
// "_gte", else the first queryable field whose type takes equality with
// "" (a JSON column takes no filter), else nil. A `_gte` example on a
// Bool or JSON column would be a request the server answers 400.
func sdkExampleFilter(fields []cliField) (field *cliField, op string) {
	for i := range fields {
		if !fields[i].NoQuery && cliFieldAcceptsGte(fields[i]) {
			f := fields[i]
			return &f, "_gte"
		}
	}
	for i := range fields {
		if !fields[i].NoQuery && !fields[i].NoEq {
			f := fields[i]
			return &f, ""
		}
	}
	return nil, ""
}

// cliFieldAcceptsGte reports whether the field's derived operator set
// contains the greater-or-equal suffix — the same derivation the CLI's
// list table uses, so the readmes and the CLI cannot disagree.
func cliFieldAcceptsGte(f cliField) bool {
	for _, op := range f.FilterOps {
		if op.Param == "_gte" {
			return true
		}
	}
	return false
}

// sdkGenerator adapts `generate sdk` to the codegen registry so a generator
// entry named "sdk" in gofastr.settings.yml also runs under
// `gofastr generate --config` (the runner errors on unregistered names).
type sdkGenerator struct{}

func (sdkGenerator) Name() string { return "sdk" }

func (sdkGenerator) Generate(_ context.Context, genCtx *codegen.Context, cfg codegen.GeneratorConfig) ([]codegen.GeneratedFile, error) {
	dir := genCtx.ProjectDir
	if dir == "" {
		dir = "."
	}
	decls, err := ReadAppDecls(dir)
	if err != nil {
		return nil, err
	}
	if len(decls) == 0 {
		return nil, fmt.Errorf("no entities package found in %s", dir)
	}
	// splitCLIEntries already decoded this entry with its index; -1 only
	// drops the index from an error an embedder's config would reach.
	opts, err := decodeSDKEntry(-1, cfg)
	if err != nil {
		return nil, err
	}
	// The runner prefixes output itself (cfg.Output); outDir only matters
	// for the direct command path.
	opts.OutDir = "gen/sdk"

	spec, err := buildSDKSpec(decls, &opts)
	if err != nil {
		return nil, err
	}
	files, err := renderSDKFiles(spec, opts.targets, true)
	if err != nil {
		return nil, err
	}
	out := make([]codegen.GeneratedFile, 0, len(files))
	for _, f := range files {
		out = append(out, codegen.GeneratedFile{Path: f.Name, Content: f.Content})
	}
	return out, nil
}
