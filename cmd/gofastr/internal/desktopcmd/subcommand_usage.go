package desktopcmd

import (
	"fmt"
)

func printDesktopUsage() {
	fmt.Println(`Usage: gofastr desktop run|build|install|uninstall|types|keygen|feed [flags]

Build and run a GoFastr app as a desktop application (battery/desktop,
experimental: macOS/arm64, Windows/amd64, Linux/amd64 and Linux/arm64).

  run [--dir=<path>] [--pkg=<path>] [--watch]
        CGO_ENABLED=0 build of the package, then exec it with
        GOFASTR_DEV=1 so the dev MCP and livereload work inside the
        window. The app picks its own loopback port; there is no
        --addr. --watch rebuilds and relaunches on source changes.
  build --id=<reverse.dns> [--name=<App Name>] [--icon=<png>]
        [--pkg=<path>] [--version=<x.y.z>]
        [--sign=<identity>|--no-sign] [-o=<dir>]
        [--notarize] [--notary-profile=<name>] [--entitlements=<plist>]
        [--scheme=<scheme>] [--format=executable|tar.gz (Linux only)]
        [--launch-args=<args>] [--ldflags=<flags>]
        On Linux, writes <o>/<Name> as a CGO-free ELF executable for
        the current architecture (or GOARCH=amd64/arm64). Install GTK 3
        and WebKitGTK 4.1 on the target machine. --format=tar.gz opts
        into <o>/<id>-<version>-linux-<arch>.tar.gz: the executable,
        a PNG icon (--icon or generated), launch.sh, an inert .desktop.in
        template, manifest.json, and runtime README. No libraries,
        installer, signing, or URL-scheme registration are bundled.
        --scheme embeds opt-in cold/warm URL delivery via an existing
        local Unix D-Bus session bus. Pass URLs as executable/launch.sh
        arguments; no browser or OS protocol association is installed.
        On macOS, cross-compiles (darwin/arm64, -trimpath, -s -w) and
        writes <o>/<Name>.app with Info.plist, the binary, PkgInfo, and
        an icon.icns built in pure Go from the PNG (no iconutil). Default
        -o is dist/, the repo's sanctioned build output dir. The icon
        defaults to a generated flat square. Signing: ad-hoc
        (codesign --force --deep --sign -) by default when codesign
        is on PATH -- enough for notifications --, --sign for a real
        identity, --no-sign to skip; a signing error is printed, never
        fatal. --notarize (needs --sign <Developer ID Application
        identity>; ad-hoc cannot be notarized) signs under the
        hardened runtime with a secure timestamp and an entitlements
        plist (generated empty <dict/> by default: a Go binary hosting
        a WKWebView needs no JIT entitlement), zips <Name>.zip in pure
        Go next to the .app, runs xcrun notarytool submit --wait with
        the keychain profile from --notary-profile (default gofastr,
        stored via xcrun notarytool store-credentials), staples the
        ticket with xcrun stapler staple, re-zips so the archive
        carries the staple, and FAILS the build if any step fails.
        On macOS, --scheme writes CFBundleURLTypes so the OS hands
        gofastr-notes://... links to the app (desktop.Config.DeepLink
        handles them).
        On Windows/amd64, builds <o>/<Name>.exe with file and product
        version details from --id, --name, and --version, embeds a
        multi-size icon resource from --icon (PNG; generated by default),
        and starts without a console window. It places the official
        WebView2Loader.dll beside the executable. The pinned loader is
        verified and fetched from NuGet; the target machine needs the
        Evergreen WebView2 Runtime installed. --scheme embeds a default
        deep-link scheme; the app registers it for the current user when
        it starts and forwards links to an existing app window. Signing
        and notarization are macOS-only.
        --launch-args=desktop bakes in the arguments a double-clicked
        executable starts with, for a binary whose desktop mode is a
        subcommand; main reads them through desktop.LaunchArgs(os.Args[1:]).
        Up to 16 whitespace-separated words. --ldflags appends linker
        flags to the build's own (--ldflags="-X main.version=1.2.3").
  install --bundle=<extracted-directory> (Linux only)
        Validates and copies a tar bundle for the current user, installs
        a menu entry and ~/.local/bin/<id> launcher, and advertises its
        embedded URL scheme. Never sets default handlers or autostart.
        Refuses existing destinations; checksums are not signatures.
  uninstall --id=<reverse.dns> (Linux only)
        Removes only an unchanged installation and its recorded launcher
        and menu entry. Preserves app data; refuses modified/unlisted
        files. Upgrade by uninstalling then installing the new bundle.
  keygen -o=<path>
        Mints the auto-update signing pair: <path> (private, 0600) and
        <path>.pub (the hex public key for desktop.UpdateConfig).
  feed --key=<path> --version=<x.y.z> --platform=<goos-goarch>
        --archive=<zip> --url=<https://...> [--notes=<text>] [-o=<dir>]
        Writes manifest.json and manifest.json.sig (ed25519 over the
        manifest bytes) with the archive's sha256 and size, the feed
        the battery's updater verifies. --version must equal the
        bundle's CFBundleShortVersionString.
  types [--pkg=<path>] [--out=desktop.d.ts]
        Builds the package, runs it once with
        GOFASTR_DESKTOP_MANIFEST=1 (the app prints its frozen manifest
        and exits before opening a window), and writes the generated
        desktop.d.ts from that manifest.`)
}
