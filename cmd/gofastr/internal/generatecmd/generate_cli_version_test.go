package generatecmd

import (
	"os/exec"
	"path/filepath"
	"testing"

	"github.com/DonaldMurillo/gofastr/cmd/gofastr/internal/clitest"
)

// `gofastr release` stamps the version with -X main.version; the
// generated CLI prints it, and "dev" when built without one.
func TestCLIVersionPrintsStampedValue(t *testing.T) {
	dir := endpointsApp(t)
	for _, c := range []struct{ ldflags, want string }{
		{"", "shop dev (generated by gofastr)\n"},
		{"-X main.version=3.1.0", "shop 3.1.0 (generated by gofastr)\n"},
	} {
		bin := clitest.TestExecutablePath(filepath.Join(t.TempDir(), "shop"))
		build := exec.Command("go", "build", "-ldflags="+c.ldflags, "-o", bin, "./cmd/shop")
		build.Dir = dir
		if out, err := build.CombinedOutput(); err != nil {
			t.Fatalf("build CLI: %v\n%s", err, out)
		}
		out, err := exec.Command(bin, "version").Output()
		if err != nil || string(out) != c.want {
			t.Errorf("ldflags %q: version printed %q, %v; want %q", c.ldflags, out, err, c.want)
		}
	}
}
