package appspec

import (
	"strings"

	"github.com/DonaldMurillo/gofastr/framework"
)

// RelationKind is one relation kind: its type, the Go constant the generator emits and its app spec spelling.
type RelationKind struct {
	Typ       framework.RelationType
	ConstName string
	Yaml      string
}

// RelationKinds is the one table mapping each framework.RelationType to its constant and spelling.
var RelationKinds = []RelationKind{
	{framework.RelHasOne, "RelHasOne", "has_one"},
	{framework.RelHasMany, "RelHasMany", "has_many"},
	{framework.RelManyToOne, "RelManyToOne", "belongs_to"},
	{framework.RelManyToMany, "RelManyToMany", "many_to_many"},
}

// FieldAutoGenerated reports whether the server fills f on create: auto_generate is set and not none.
func FieldAutoGenerated(f framework.FieldDeclaration) bool {
	auto := strings.ToLower(strings.TrimSpace(f.AutoGenerate))
	return auto != "" && auto != "none"
}
