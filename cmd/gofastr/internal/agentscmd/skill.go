package agentscmd

import (
	"bytes"
	_ "embed"
	"errors"
	"fmt"
	"io/fs"
)

// gofastrHostSkill is the source for the gofastr-host Claude Code
// skill that `gofastr init` and `gofastr agents skill` drop into a
// host project's .claude/skills/ tree.
//
// Canonical edit location is .claude/skills/gofastr-host/SKILL.md in
// the gofastr repo. cmd/gofastr/embedded/gofastr-host-skill.md is a
// byte-for-byte copy kept in sync by TestEmbeddedHostSkillMatchesRepo.
// Failing that test means the two files have drifted: copy the canon
// over.
//
//go:embed embedded/gofastr-host-skill.md
var gofastrHostSkill string

// hostSkillDir is where the gofastr-host skill lives in a project.
const hostSkillDir = ".claude/skills/gofastr-host"

// skillGenHeader is the first line inside the generated SKILL.md's
// frontmatter, the mark that an existing file is previous generator
// output and safe to replace. A SKILL.md without it looks hand-written
// and `gofastr agents skill` refuses to clobber it without --force, the
// rule the .agents/ detail files already follow (#669).
const skillGenHeader = "# AUTO-GENERATED by gofastr agents skill"

// WriteHostSkill drops the gofastr-host skill into <dir>/.claude/skills/
// gofastr-host/SKILL.md. Overwrites a previous generated copy (one whose
// frontmatter carries skillGenHeader); an existing file without the
// header is refused unless force is set. The write is confined to dir: a
// symlinked .claude or SKILL.md that leads out of the project is
// refused, never written through.
func WriteHostSkill(dir string, force bool) error {
	root, err := openProjectRoot(dir)
	if err != nil {
		return fmt.Errorf("create skill dir: %w", err)
	}
	defer root.Close()
	if err := root.MkdirAll(hostSkillDir, 0o755); err != nil {
		return fmt.Errorf("create skill dir: %w", err)
	}
	if !force {
		if existing, err := readInRoot(root, hostSkillDir+"/SKILL.md"); err == nil {
			// Line-ending tolerant: a checkout with autocrlf (or a
			// Windows write) must still recognize the file this
			// command generated, or it could never refresh its own
			// previous output.
			head := existing
			if len(head) > len(skillGenHeader)+8 {
				head = head[:len(skillGenHeader)+8]
			}
			head = bytes.ReplaceAll(head, []byte("\r\n"), []byte("\n"))
			if !bytes.HasPrefix(head, []byte("---\n"+skillGenHeader)) {
				return fmt.Errorf("refusing to overwrite %s: it lacks the generated header, so it looks hand-written. Move or delete it, or re-run with --force", hostSkillDir+"/SKILL.md")
			}
		} else if !errors.Is(err, fs.ErrNotExist) {
			return fmt.Errorf("read existing skill: %w", err)
		}
	}
	if err := replaceInRoot(root, hostSkillDir+"/SKILL.md", []byte(gofastrHostSkill), 0o644); err != nil {
		return fmt.Errorf("write skill: %w", err)
	}
	return nil
}
