// TestNodeCorpus replays the corpus canonicalized by the committed
// Node reference (the RFC 8785 Appendix A construction: key-sorted
// JSON.stringify under Node 22, sharing no code with this package).
// Regenerate with `node testdata/gen-corpus.mjs` — never edit
// corpus-expected.txt by hand.
func TestNodeCorpus(t *testing.T) {
	rawCorpus, err := os.ReadFile(filepath.Join("testdata", "corpus.json"))
	if err != nil {
		t.Fatal(err)
	}
	rawExpected, err := os.ReadFile(filepath.Join("testdata", "corpus-expected.txt"))
	if err != nil {
		t.Fatal(err)
	}
	expected := strings.Split(strings.TrimRight(string(rawExpected), "\n"), "\n")

	// Walk the corpus array with the parser to get per-element slices,
	// so each value is exercised exactly as standalone JSON input.
	var elems [][]byte
	p := &parser{data: rawCorpus}
	p.skipWS()
	if p.pos >= len(p.data) || p.data[p.pos] != '[' {
		t.Fatal("corpus.json is not an array")
	}
	p.pos++
	p.skipWS()
	for {
		if p.pos < len(p.data) && p.data[p.pos] == ']' {
			break
		}
		start := p.pos
		if _, err := p.parseValue(1); err != nil {
			t.Fatalf("corpus element %d: %v", len(elems), err)
		}
		elems = append(elems, p.data[start:p.pos])
		p.skipWS()
		if p.pos < len(p.data) && p.data[p.pos] == ',' {
			p.pos++
			p.skipWS()
		}
	}
	if len(elems) != len(expected) {
		t.Fatalf("corpus has %d values but %d expected lines", len(elems), len(expected))
	}
	for i, el := range elems {
		got, err := CanonicalizeJSON(el)
		if err != nil {
			t.Fatalf("corpus[%d]: %v", i, err)
		}
		wantBytes, err := hex.DecodeString(expected[i])
		if err != nil {
			t.Fatalf("expected[%d]: bad hex: %v", i, err)
		}
		if !bytes.Equal(got, wantBytes) {
			t.Errorf("corpus[%d] differs from Node reference\n got: %s\nwant: %s", i, got, wantBytes)
		}
	}
}

// ─── Canonicalize (Go values) ───────────────────────────────────────

func TestCanonicalizeValues(t *testing.T) {
	cases := []struct {
		name string
		in   any
		want string
	}{
		{"map", map[string]any{"b": 1, "a": 2}, `{"a":2,"b":1}`},
		{"nested", map[string]any{"z": map[string]any{"b": true, "a": false}}, `{"z":{"a":false,"b":true}}`},
		{"slice", []any{3, 1, 2}, `[3,1,2]`},
		{"empty obj/slice", []any{map[string]any{}, []any{}}, `[{},[]]`},
		{"string escapes", map[string]string{"k": "a\"b\\c\n\t\r\b\fd"}, `{"k":"a\"b\\c\n\t\r\b\fd"}`},
		{"control escapes", map[string]string{"k": "\x01"}, "{\"k\":\"\\u0001\"}"},
		{"slash literal", map[string]string{"k": "a/b"}, `{"k":"a/b"}`},
		{"del literal", map[string]string{"k": "a\x7f"}, "{\"k\":\"a\x7f\"}"},
		{"number formats", map[string]any{
			"a": 1e21, "b": 1e-7, "c": 100.0, "d": -0.0,
			"e": json.Number("333333333.33333329"),
		}, `{"a":1e+21,"b":1e-7,"c":100,"d":0,"e":333333333.3333333}`},
		{"struct order irrelevant", struct {
			B int `json:"b"`
			A int `json:"a"`
		}{1, 2}, `{"a":2,"b":1}`},
		{"nil", nil, `null`},
		{"bools", []any{true, false}, `[true,false]`},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			got, err := Canonicalize(tc.in)
			if err != nil {
				t.Fatalf("Canonicalize: %v", err)
			}
			if string(got) != tc.want {
				t.Errorf("\n got %s\nwant %s", got, tc.want)
			}
		})
	}
}

