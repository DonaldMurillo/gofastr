func runNumberVectors(t *testing.T, path string) {
	t.Helper()
	raw, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	lines := strings.Split(strings.TrimRight(string(raw), "\n"), "\n")
	for i, line := range lines {
		hexStr, want, ok := strings.Cut(line, ",")
		if !ok {
			t.Fatalf("%s:%d: malformed line %q", path, i+1, line)
		}
		bits, ok := new(big.Int).SetString(hexStr, 16)
		if !ok {
			t.Fatalf("%s:%d: bad hex %q", path, i+1, hexStr)
		}
		f := math.Float64frombits(bits.Uint64())
		if got := formatNumber(f); got != want {
			t.Errorf("%s:%d: formatNumber(%s = %v):\n got %q\nwant %q", path, i+1, hexStr, f, got, want)
		}
		// The same value must survive the full public path: a JSON
		// literal parsed and re-serialized canonically. 'g' formatting
		// of subnormals can underflow on parse; those skip this half.
		lit := strconv.FormatFloat(f, 'g', -1, 64)
		if _, err := strconv.ParseFloat(lit, 64); err != nil {
			continue
		}
		got2, err := CanonicalizeJSON([]byte(lit))
		if err != nil {
			t.Fatalf("%s:%d: CanonicalizeJSON(%q): %v", path, i+1, lit, err)
		}
		if string(got2) != want {
			t.Errorf("%s:%d: CanonicalizeJSON(%q):\n got %q\nwant %q", path, i+1, lit, got2, want)
		}
	}
}

// TestRFC8785SortExample pins the property-sorting example from
// RFC 8785 §3.2.3: the expected order of the sample keys.
func TestRFC8785SortExample(t *testing.T) {
	keys := []string{"\r", "1", "", "ö", "€", "\U0001F600", "דּ"}
	sortKeysByUTF16(keys)
	want := []string{"\r", "1", "", "ö", "€", "\U0001F600", "דּ"}
	for i := range keys {
		if keys[i] != want[i] {
			t.Fatalf("position %d: got %q want %q", i, keys[i], want[i])
		}
	}
}

// TestUTF16SortDivergence proves the sort is UTF-16 code-unit order, not
// UTF-8 byte order: U+10000+ keys (surrogate pairs 0xD800–0xDBFF) sort
// BEFORE U+E000–U+FFFF even though their UTF-8 bytes sort after.
func TestUTF16SortDivergence(t *testing.T) {
	if utf16.Encode([]rune("😀"))[0] != 0xD83D {
		t.Fatal("test premise broken")
	}
	keys := []string{"\ue000", "😀"}
	sortKeysByUTF16(keys)
	if keys[0] != "😀" {
		t.Fatalf("UTF-16 order must put the emoji first, got %q", keys[0])
	}
	// Via the full parser: keys are emitted in sorted position.
	in := []byte("{\"\uE000\":\"after-bytes\",\"😀\":\"first-bytes\"}")
	got, err := CanonicalizeJSON(in)
	if err != nil {
		t.Fatal(err)
	}
	want := "{\"😀\":\"first-bytes\",\"\uE000\":\"after-bytes\"}"
	if string(got) != want {
		t.Fatalf("got %s want %s", got, want)
	}
}

