// ─── Gate A: RFC 8785 reference suite (cyberphone testdata) ─────────

// TestReferenceSuite runs the six official input/expected pairs from
// the RFC 8785 reference implementation repository (testdata/vectors,
// see testdata/README.md for provenance), byte-for-byte against both
// the JSON and the hex forms.
func TestReferenceSuite(t *testing.T) {
	names := []string{"arrays", "french", "structures", "unicode", "values", "weird"}
	for _, name := range names {
		t.Run(name, func(t *testing.T) {
			in, err := os.ReadFile(filepath.Join("testdata", "vectors", "input", name+".json"))
			if err != nil {
				t.Fatal(err)
			}
			want, err := os.ReadFile(filepath.Join("testdata", "vectors", "output", name+".json"))
			if err != nil {
				t.Fatal(err)
			}
			want = bytes.TrimSuffix(want, []byte("\n"))

			got, err := CanonicalizeJSON(in)
			if err != nil {
				t.Fatalf("CanonicalizeJSON: %v", err)
			}
			if !bytes.Equal(got, want) {
				t.Errorf("canonical bytes differ\n got: %q\nwant: %q", got, want)
			}

			// The outhex file pins the same expectation as hex bytes;
			// check it independently so the two fixtures can't drift.
			hexRaw, err := os.ReadFile(filepath.Join("testdata", "vectors", "outhex", name+".txt"))
			if err != nil {
				t.Fatal(err)
			}
			var hexBytes []byte
			for _, field := range strings.Fields(string(hexRaw)) {
				b, err := hex.DecodeString(field)
				if err != nil {
					t.Fatalf("bad hex field %q: %v", field, err)
				}
				hexBytes = append(hexBytes, b...)
			}
			if !bytes.Equal(got, hexBytes) {
				t.Errorf("canonical bytes differ from outhex\n got: %x\nwant: %x", got, hexBytes)
			}
		})
	}
}

