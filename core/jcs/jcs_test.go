func TestRejectedJSON(t *testing.T) {
	cases := []struct {
		name string
		in   string
		want string // substring of the expected error
	}{
		{"duplicate keys", `{"a":1,"a":2}`, "duplicate object key"},
		{"duplicate nested", `{"x":{"a":1,"a":2}}`, "duplicate object key"},
		{"duplicate after ws", `{ "a" : 1 , "a" : 2 }`, "duplicate object key"},
		{"lone high surrogate", `"\ud800"`, "unpaired high surrogate"},
		{"lone low surrogate", `"a\udead"`, "unpaired low surrogate"},
		{"high surrogate then non-escape", `"\ud800x"`, "unpaired high surrogate"},
		{"surrogate then bad low", `"\ud800\ud800"`, "unpaired high surrogate"},
		{"invalid utf8 raw", "\"a\xffb\"", "invalid UTF-8"},
		{"raw control in string", "\"a\x01b\"", "raw control character"},
		{"raw tab in string", "\"a\tb\"", "raw control character"},
		{"leading zero", `{"a":01}`, "expected ',' or '}'"},
		{"plus number", `{"a":+1}`, "unexpected character"},
		{"bare dot", `{"a":.5}`, "unexpected character"},
		{"trailing dot", `{"a":1.}`, "digit required"},
		{"dot no digits", `{"a":1.e3}`, "digit required"},
		{"bare exponent", `{"a":1e}`, "digit required"},
		{"e plus no digits", `{"a":1e+}`, "digit required"},
		{"minus only", `{"a":-}`, "invalid number"},
		{"overflow to inf", `{"a":1e999}`, "overflows to Infinity"},
		{"negative overflow", `{"a":-1e999}`, "overflows to Infinity"},
		{"hex garbage", `0x10`, "unexpected trailing data"},
		{"empty input", ``, "unexpected end of input"},
		{"whitespace only", `   `, "unexpected end of input"},
		{"trailing garbage", `{"a":1} x`, "unexpected trailing data"},
		{"trailing comma obj", `{"a":1,}`, "expected object key string"},
		{"trailing comma arr", `[1,]`, "unexpected character"},
		{"unterminated obj", `{"a":1`, "unterminated object"},
		{"unterminated arr", `[1`, "unterminated array"},
		{"unterminated string", `"abc`, "unterminated string"},
		{"bad literal", `tru`, "invalid literal"},
		{"NaN literal", `NaN`, "unexpected character"},
		{"Infinity literal", `Infinity`, "unexpected character"},
		{"no colon", `{"a" 1}`, "expected ':'"},
		{"single quotes", `'a'`, "unexpected character"},
		{"comment", `{"a":1}/*x*/`, "unexpected trailing data"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			_, err := CanonicalizeJSON([]byte(tc.in))
			if err == nil {
				t.Fatalf("CanonicalizeJSON(%q) succeeded, want error containing %q", tc.in, tc.want)
			}
			if !strings.Contains(err.Error(), tc.want) {
				t.Errorf("CanonicalizeJSON(%q) error %q, want substring %q", tc.in, err, tc.want)
			}
		})
	}
}

func TestRejectedNumbers(t *testing.T) {
	for _, tc := range []struct {
		name string
		f    float64
	}{
		{"NaN", math.NaN()},
		{"+Inf", math.Inf(1)},
		{"-Inf", math.Inf(-1)},
	} {
		t.Run(tc.name, func(t *testing.T) {
			if _, err := Canonicalize(tc.f); err == nil {
				t.Fatalf("Canonicalize(%s) succeeded, want error", tc.name)
			}
		})
	}
	// RFC 8785 Appendix B notes (3): NaN/Infinity bit patterns are not
	// valid JSON and must never canonicalize.
	if got := formatNumber(math.Float64frombits(0x7fffffffffffffff)); got != "NaN" {
		t.Errorf("formatNumber(NaN-bits) = %q, want NaN placeholder (unreachable guard)", got)
	}
}

func TestUnderflowCanonicalizesToZero(t *testing.T) {
	// ECMAScript: JSON.parse("1e-400") → 0. Same rule here.
	for _, lit := range []string{"1e-400", "-1e-400", "5e-325"} {
		got, err := CanonicalizeJSON([]byte(lit))
		if err != nil {
			t.Fatalf("CanonicalizeJSON(%q): %v", lit, err)
		}
		if string(got) != "0" {
			t.Errorf("CanonicalizeJSON(%q) = %s, want 0", lit, got)
		}
	}
}

func TestDepthLimit(t *testing.T) {
	deep := strings.Repeat("[", 600) + strings.Repeat("]", 600)
	if _, err := CanonicalizeJSON([]byte(deep)); err == nil || !strings.Contains(err.Error(), "nesting") {
		t.Errorf("depth 600: err = %v, want nesting error", err)
	}
	ok := strings.Repeat("[", 100) + strings.Repeat("]", 100)
	if _, err := CanonicalizeJSON([]byte(ok)); err != nil {
		t.Errorf("depth 100: %v", err)
	}
}

// TestWhitespaceInsensitivity: canonical form is a function of the
// parsed value, not the input layout.
func TestWhitespaceInsensitivity(t *testing.T) {
	a := []byte("{ \"b\" : [ 1 , 2 ] ,\n\"a\" : { } }")
	b := []byte(`{"b":[1,2],"a":{}}`)
	ca, err := CanonicalizeJSON(a)
	if err != nil {
		t.Fatal(err)
	}
	cb, err := CanonicalizeJSON(b)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(ca, cb) {
		t.Errorf("layouts differ canonically:\n%s\n%s", ca, cb)
	}
	if string(ca) != `{"a":{},"b":[1,2]}` {
		t.Errorf("got %s", ca)
	}
}

func TestNumberLiteralFormsCollapse(t *testing.T) {
	// Same double, different literals, one canonical form.
	lits := []string{"1E2", "1e2", "100", "100.0", "100.00", "1e+2", "1.0e2"}
	for _, lit := range lits {
		got, err := CanonicalizeJSON([]byte(lit))
		if err != nil {
			t.Fatalf("CanonicalizeJSON(%q): %v", lit, err)
		}
		if string(got) != "100" {
			t.Errorf("CanonicalizeJSON(%q) = %s, want 100", lit, got)
		}
	}
}

