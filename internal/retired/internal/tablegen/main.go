// Command tablegen writes internal/retired's retired-name table
// (retired_table.gen.go) from internal/upgrade's migration registry:
// every class (strings.classes, css.classes) and attribute
// (strings.attrs) a breaking note names, kept the way retired.New keeps
// them — the kit's namespaces only, first note wins.
//
// The table exists so the dev-mode retired-markup middleware that
// framework and framework/uihost install does not link the registry:
// with the registry embedded in those packages, every release-note edit
// re-ran nearly the whole test suite. TestTableIsCurrent, in this
// package, fails when the table no longer matches the registry, and a
// release-note edit selects it because this package imports the
// registry.
//
// Run it through go generate (the directive is in internal/retired's
// set.go):
//
//	go generate ./internal/retired
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"strconv"

	"github.com/DonaldMurillo/gofastr/internal/retired"
	"github.com/DonaldMurillo/gofastr/internal/upgrade"
)

// regenerate is the command a stale table's failure names.
const regenerate = "go generate ./internal/retired"

func main() {
	log.SetFlags(0)
	out := flag.String("out", "", "file to write the table to (go generate passes retired_table.gen.go)")
	flag.Parse()
	if *out == "" {
		log.Fatal("tablegen: -out is required; run " + regenerate)
	}
	reg, err := upgrade.Load()
	if err != nil {
		log.Fatalf("tablegen: load migration registry: %v", err)
	}
	src, err := render(reg)
	if err != nil {
		log.Fatalf("tablegen: %v", err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatalf("tablegen: %v", err)
	}
}

// candidates lists every name a breaking note retires, in registry
// order: releases oldest first, notes as written, and within a note its
// strings.classes, then css.classes, then strings.attrs. Non-breaking
// notes contribute nothing: their spellings are not retired. Notes are
// shared, so every name a note retires carries the same *retired.Note.
func candidates(reg *upgrade.Registry) []retired.Entry {
	var out []retired.Entry
	for i := range reg.Releases {
		for _, note := range reg.Releases[i].Notes {
			if !note.Breaking {
				continue
			}
			n := &retired.Note{Version: note.Version, Change: note.Change}
			for _, name := range note.Find.Strings.Classes {
				out = append(out, retired.Entry{Kind: "class", Name: name, Note: n})
			}
			for _, name := range note.Find.CSS.Classes {
				out = append(out, retired.Entry{Kind: "class", Name: name, Note: n})
			}
			for _, name := range note.Find.Strings.Attrs {
				out = append(out, retired.Entry{Kind: "attr", Name: name, Note: n})
			}
		}
	}
	return out
}

// render writes the table: the notes the kept names point at, in first
// use order, and the kept names in the order retired.New kept them.
func render(reg *upgrade.Registry) ([]byte, error) {
	kept := retired.New(candidates(reg)).Entries()
	index := map[*retired.Note]int{}
	var notes []*retired.Note
	for _, e := range kept {
		if _, ok := index[e.Note]; !ok {
			index[e.Note] = len(notes)
			notes = append(notes, e.Note)
		}
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/retired/internal/tablegen from internal/upgrade's migration registry; DO NOT EDIT.\n")
	b.WriteString("// Regenerate with: " + regenerate + "\n\n")
	b.WriteString("package retired\n\n")
	b.WriteString("// tableNotes are the breaking notes the retired names in table cite.\n")
	b.WriteString("var tableNotes = [...]Note{\n")
	for _, n := range notes {
		fmt.Fprintf(&b, "\t{Version: %s, Change: %s},\n", strconv.Quote(n.Version), strconv.Quote(n.Change))
	}
	b.WriteString("}\n\n")
	b.WriteString("// table is every retired kit name, in the order New keeps them.\n")
	b.WriteString("var table = [...]Entry{\n")
	for _, e := range kept {
		fmt.Fprintf(&b, "\t{Kind: %s, Name: %s, Note: &tableNotes[%d]},\n", strconv.Quote(e.Kind), strconv.Quote(e.Name), index[e.Note])
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}
